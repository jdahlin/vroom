#!/bin/sh
# gen-ppdata.sh LINUX_SRC   (writes ppdata.inc and ppdata-predef.inc next to it)
#
# Data the preprocessor takes from clang once, like caps.c: the predefined
# macros for the two targets vcc builds for (the kernel: aarch64-linux-gnu;
# host tools: arm64 darwin), darwin's system include directories, and the
# answers to every feature-test query (__has_attribute(x), __is_target_os(x),
# ...) that the kernel source, the macOS SDK and clang's own headers make.
# vcc itself never runs clang.
set -e
L=${1:?linux source}
CL=${CLANG:-/opt/homebrew/opt/llvm/bin/clang}
D=$(dirname "$0")
T=${KEEP:-$(mktemp -d)}; mkdir -p $T; [ -n "$KEEP" ] || trap "rm -rf $T" EXIT
FL="--target=aarch64-linux-gnu -std=gnu11 -O2 -fno-PIE -mlittle-endian -fshort-wchar -funsigned-char -fno-common -fno-strict-aliasing -mgeneral-regs-only -fno-asynchronous-unwind-tables -fno-unwind-tables -mbranch-protection=none -fno-delete-null-pointer-checks -fno-stack-protector -fno-omit-frame-pointer -fno-strict-overflow"
FH="-std=gnu11 -O2"
cstr() { sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/	"/' -e 's/$/\\n"/'; }

SYS=$($CL $FH -E -v -x c /dev/null 2>&1 | sed -n '/<\.\.\.> search starts/,/End of search/p' | sed '1d;$d')
SDKINC=$(echo "$SYS" | grep -v framework | sed 's/^ *//' | tail -1)
RESINC=$(echo "$SYS" | grep -v framework | sed 's/^ *//' | head -1)

{
	echo "/* generated by gen-ppdata.sh from $($CL --version | head -1) */"
	echo "static const char predef_aarch64_linux[] ="
	$CL $FL -dM -E -x c /dev/null | LC_ALL=C sort | cstr
	echo "	;"
	echo "static const char predef_darwin[] ="
	$CL $FH -dM -E -x c /dev/null | LC_ALL=C sort | cstr
	echo "	;"
	echo "static const char predef_undef_c[] ="
	$CL -undef -dM -E -x c /dev/null | LC_ALL=C sort | cstr
	echo "	;"
	echo "static const char predef_undef_asm[] ="
	$CL -undef -dM -E -x assembler-with-cpp /dev/null | LC_ALL=C sort | cstr
	echo "	;"
	echo "static const char *const sysdirs_darwin[] = {"
	echo "$SYS" | grep -v framework | sed 's/^ *\(.*\)$/	"\1",/'
	echo "};"
	echo "static const char *const fwdirs_darwin[] = {"
	echo "$SYS" | grep framework | sed 's/^ *\(.*\) (framework directory)$/	"\1",/'
	echo "};"
} > "$D/ppdata-predef.inc"

# Candidate arguments: the literal queries, every identifier in the SDK and
# clang's headers (they wrap queries in macros: __supports_builtin(x) ...),
# and every __identifier in the kernel tree.  Each is asked of clang for
# each name-taking query; only nonzero answers are kept (the rest are 0).
Q='__has_(attribute|builtin|feature|extension|c_attribute|cpp_attribute|declspec_attribute|constexpr_builtin)|__is_target_(arch|os|vendor|environment|variant_os|variant_environment)'
grep -rhoE "($Q)[[:space:]]*\\([[:space:]]*[A-Za-z_0-9:-]+" --include='*.h' --include='*.c' --include='*.S' \
	"$L" "$SDKINC" "$RESINC" 2>/dev/null | tr -d ' \t' > $T/lit
{
	grep -rhoE '[A-Za-z_][A-Za-z_0-9]*' "$SDKINC" "$RESINC" 2>/dev/null
	grep -rhoIE '\b__[A-Za-z_0-9]+' --include='*.h' --include='*.c' "$L" 2>/dev/null
	sed 's/^[^(]*(//' $T/lit
} | LC_ALL=C sort -u > $T/ids0
# names that are macros themselves would expand (and may swallow lines)
{ $CL $FL -dM -E -x c /dev/null; $CL $FH -dM -E -x c /dev/null; } | awk '{ sub(/\(.*/, "", $2); print $2 }' | LC_ALL=C sort -u > $T/macros
LC_ALL=C comm -23 $T/ids0 $T/macros | grep -vE '^(__has_|__is_target_|__building_module$|_Pragma$|defined$|__FILE__$|__LINE__$|__COUNTER__$|__DATE__$|__TIME__$|__TIMESTAMP__$|__BASE_FILE__$|__FILE_NAME__$|__INCLUDE_LEVEL__$|__is_identifier$)' > $T/ids
for q in __has_builtin __has_attribute __has_feature __has_extension __has_c_attribute __has_declspec_attribute __has_constexpr_builtin; do
	sed "s/.*/\"$q\" \"&\" $q(&)/" $T/ids
done > $T/q.c
sed -n 's/^\(__is_target_[a-z_]*\)(\(.*\)$/"\1" "\2" \1(\2)/p' $T/lit | LC_ALL=C sort -u >> $T/q.c
sed -n 's/^\(__has_[a-z_]*\)(\(.*::.*\)$/"\1" "\2" \1(\2)/p' $T/lit | LC_ALL=C sort -u >> $T/q.c
$CL $FL -ferror-limit=0 -E -P -x c $T/q.c 2>/dev/null | awk 'NF==3 && $3 ~ /^[0-9]+$/' > $T/linux
$CL $FH -ferror-limit=0 -E -P -x c $T/q.c 2>/dev/null | awk 'NF==3 && $3 ~ /^[0-9]+$/' > $T/darwin
exec > "$D/ppdata.inc"
echo "/* generated by gen-ppdata.sh from $($CL --version | head -1); sorted for bsearch */"
echo "static const struct { const char *q, *name; int v[2]; /* aarch64-linux, darwin */ } has_tab[] = {"
awk 'FNR==NR { L[$1" "$2] = $3; next } { D[$1" "$2] = $3 }
     END { for (k in L) K[k]; for (k in D) K[k];
	   for (k in K) { l = (k in L) ? L[k] : 0; d = (k in D) ? D[k] : 0; if (l != "0" || d != "0") print k, l, d } }' \
	$T/linux $T/darwin | LC_ALL=C sort -u -k1,1 -k2,2 | awk '{ printf "\t{ %s, %s, { %s, %s } },\n", $1, $2, $3, $4 }'
echo "};"
