#!/bin/sh
# attrnames.inc: the GNU attribute names clang knows per target (its
# __has_attribute answer), for -Wunknown-attributes.  Names come from clang's
# tablegen output (AttrParsedAttrKinds.inc, GNU syntax); run once per clang.
set -e
CL=${CLANG:-/opt/homebrew/opt/llvm/bin/clang}
INC=${INC:-$(dirname $(dirname $CL))/include/clang/Sema/AttrParsedAttrKinds.inc}
D=$(dirname "$0")
T=$(mktemp -d); trap "rm -rf $T" EXIT
awk '/AS_GNU == Syntax/{f=1;next} f&&/if \(AttributeCommonInfo::AS_/{exit} f' "$INC" |
	grep -o '// "[^"]*"' | sed 's/^\/\/ "//;s/"$//' | LC_ALL=C sort -u > $T/names
sed 's/.*/"&" __has_attribute(&)/' $T/names > $T/q.c
for t in aarch64-linux-gnu arm64-apple-macosx wasm64-unknown-emscripten; do
	$CL --target=$t -E -P -x c $T/q.c | awk 'NF==2' > $T/$t
done
exec > "$D/attrnames.inc"
echo "/* generated by gen-attrnames.sh from $($CL --version | head -1); sorted for bsearch */"
echo "/* bit 0: aarch64-linux, 1: darwin, 2: wasm (__has_attribute != 0) */"
echo "static const struct { const char *name; uint8_t on; } gnu_attrs[] = {"
paste $T/aarch64-linux-gnu $T/arm64-apple-macosx $T/wasm64-unknown-emscripten |
	awk '{ m = ($2 != "0") + 2 * ($4 != "0") + 4 * ($6 != "0"); if (m) printf "\t{ %s, %d },\n", $1, m }'
echo "};"
echo "/* clang's AttributeSpellingList.inc: the candidates of the typo correction */"
echo "static const char *const attr_spellings[] = {"
sed -n 's/^ATTR_NAME(\(".*"\))$/	\1,/p' "$(dirname $(dirname $INC))/Basic/AttributeSpellingList.inc"
echo "};"
