#!/bin/sh
# Generates warnings.inc: warning groups that vcc accepts.
# As long as the backend is clang they must be a subset of clang's groups.
set -e
DIAGTOOL=${DIAGTOOL:-/opt/homebrew/opt/llvm/bin/diagtool}
{
	echo "/* generated by gen-warnings.sh from \`diagtool tree\`; do not edit */"
	"$DIAGTOOL" tree 2>/dev/null | sed -E 's/^[ ]*-W//; s/ .*//' | grep -E '^[a-z0-9]' |
		LC_ALL=C sort -u | sed 's/.*/"&",/'
} > warnings.inc
