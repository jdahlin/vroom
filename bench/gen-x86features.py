#!/usr/bin/env python3
"""Regenerate static x86-64 LLVM feature facts and Clang predefined macros.
Requires matching llvm-config/clang and clang/lib/Basic/Targets/X86.cpp.
No generated file needs LLVM at compiler runtime. Parallel queries capped at six.
"""
import argparse, concurrent.futures, hashlib, json, pathlib, re, shlex, subprocess, tempfile
ROOT=pathlib.Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--cxx',help='C++ compiler for the one-time LLVM probe');p.add_argument('--llvm-config',default='llvm-config');p.add_argument('--clang',default='clang');p.add_argument('--clang-source',type=pathlib.Path,required=True)
a=p.parse_args()
def run(args): return subprocess.check_output(args,text=True)
source=a.clang_source.read_text()
version=run([a.clang,'--version']).splitlines()[0]
with tempfile.TemporaryDirectory() as td:
 exe=str(pathlib.Path(td)/'probe')
 flags=shlex.split(run([a.llvm_config,'--cxxflags','--ldflags','--libs','targetparser','support','--system-libs']))
 run([a.cxx or str(pathlib.Path(run([a.llvm_config,'--bindir']).strip())/'clang++'),str(ROOT/'bench/data/x86features-probe.cpp'),*flags,'-o',exe])
 raw=run([exe])
cpus={};deps={};names=set()
for line in raw.splitlines():
 q=line.split()
 if q[0]=='CPU':cpus[q[1]]=set(q[2:]);names.update(q[2:])
 else:
  ds={x.split('=')[0] for x in q[3:]};deps[q[1],int(q[2])]=ds|{q[1]};names.update(ds);names.add(q[1])
# Preserve the TargetParser sorted IDs; frontend-only names follow in sorted order.
original=sorted(names)
valid=source.split('bool X86TargetInfo::isValidFeatureName',1)[1].split('bool X86TargetInfo::hasFeature',1)[0]
handled=dict((h,f) for f,h in re.findall(r'Feature == "\+([^"]+)"\) \{\s*(Has\w+)\s*= true;',source))
extras=set(re.findall(r'\.Case\("([^"]+)", true\)',valid))|set(handled.values())
extras-={'sse4','general-regs-only'} # ordered resolver actions, not stored features
names=original+sorted(extras-set(original));idx={n:i for i,n in enumerate(names)};words=(len(names)+63)//64
if words!=3: raise SystemExit(f'Update x86_features storage for {words} words')
def mask(fs):
 v=[0]*words
 for f in fs:v[idx[f]//64]|=1<<(idx[f]%64)
 return '{{'+','.join('UINT64_C(0x%x)'%x for x in v)+'}}'
provenance=f'/* Generated by bench/gen-x86features.py.\n * {version}\n * X86.cpp SHA256 {hashlib.sha256(source.encode()).hexdigest()}\n * x86_64-unknown-linux-gnu; no runtime LLVM dependency. */\n'
out=provenance+f'#define X86_FEATURE_COUNT {len(names)}\n'
for n in names:out+='#define X86_FEATURE_'+re.sub('[^A-Z0-9]','_',n.upper())+' '+str(idx[n])+'\n'
out+='#define X86_FEATURE_SSE41 X86_FEATURE_SSE4_1\n#define X86_FEATURE_SSE42 X86_FEATURE_SSE4_2\n'
out+='static const char *const x86_feature_names[] = {'+','.join(json.dumps(n) for n in names)+'};\n'
out+='static const x86_features x86_feature_deps[][2] = {\n'+''.join('{'+mask(deps.get((n,0),{n}))+','+mask(deps.get((n,1),{n}))+'},\n' for n in names)+'};\n'
out+='static const struct { const char *name; x86_features features; } x86_cpus[] = {\n'+''.join('{'+json.dumps(n)+','+mask(fs)+'},\n' for n,fs in cpus.items())+'};\n'
# Public CLI and target attributes expose a narrower namespace than LLVM's
# feature map. Probe both rather than accepting every internal backend name.
def public_names(name):
 cli=subprocess.run([a.clang,'--target=x86_64-unknown-linux-gnu','-m'+name,'-Werror','-fsyntax-only','-x','c','/dev/null'],capture_output=True).returncode==0
 src='__attribute__((target("'+name+'"))) int probe(void) { return 0; }\n'
 attr=subprocess.run([a.clang,'--target=x86_64-unknown-linux-gnu','-Werror','-fsyntax-only','-x','c','-'],input=src,text=True,capture_output=True).returncode==0
 return name,cli,attr
with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:public=list(pool.map(public_names,names))
cli_names={n for n,c,t in public if c};attr_names={n for n,c,t in public if t}
out+='static const x86_features x86_cli_valid = '+mask(cli_names)+';\n'
out+='static const x86_features x86_attr_valid = '+mask(attr_names)+';\n'
# Clang emits simple HasFeature predicates, plus the enumerated SSE/XOP levels.
body=source.split('// Target properties.',1)[1].split('bool X86TargetInfo::isValidFeatureName',1)[0]
macros={}
for h,macro in re.findall(r'if \((Has\w+)\)\s*(?:\{\s*)?Builder.defineMacro\("([^"]+)"\)',body):
 if h in handled:macros[macro]={handled[h]}
for f,m in [('avx10.1','__AVX10_1_512__'),('avx10.2','__AVX10_2_512__'),('sse','__SSE__'),('sse','__SSE_MATH__'),('sse2','__SSE2__'),('sse2','__SSE2_MATH__'),('sse3','__SSE3__'),('ssse3','__SSSE3__'),('sse4.1','__SSE4_1__'),('sse4.2','__SSE4_2__'),('avx','__AVX__'),('avx2','__AVX2__'),('avx512f','__AVX512F__'),('sse4a','__SSE4A__'),('fma4','__FMA4__'),('xop','__XOP__'),('sahf','__LAHF_SAHF__'),('cx16','__GCC_HAVE_SYNC_COMPARE_AND_SWAP_16')]:macros[m]={f}
macros['__APX_F__']=set('egpr push2pop2 ppx ndd ccmp nf zu jmpabs'.split())
macros['__APX_INLINE_ASM_USE_GPR32__']={'egpr','inline-asm-use-gpr32'}
def query(cpu):
 text=run([a.clang,'--target=x86_64-unknown-linux-gnu','-march='+cpu,'-dM','-E','-x','c','/dev/null'])
 return dict(re.findall(r'^#define (\S+) ?(.*)$',text,re.M))
with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool: snapshots=dict(zip(cpus,pool.map(query,cpus)))
base=snapshots['x86-64']
# Source snapshots can be newer than the installed compiler. Keep only predicates
# witnessed by its actual preprocessor with all required features enabled.
def witness(item):
 m,fs=item
 cmd=[a.clang,'--target=x86_64-unknown-linux-gnu','-dM','-E','-x','c','/dev/null']
 for f in sorted(fs):cmd+=['-Xclang','-target-feature','-Xclang','+'+f]
 return m, bool(re.search(r'^#define '+re.escape(m)+r'(?: |$)',run(cmd),re.M))
with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
 for m,present in pool.map(witness,list(macros.items())):
  if not present:del macros[m]
values={m:'1' for m in macros}
# _Float16 predefines are emitted only when SSE2 is enabled on x86-64.
for m,v in base.items():
 if m.startswith('__FLT16_'):macros[m]={'sse2'};values[m]=v
# CPU identity macros are lowercase and are the remaining CPU-sensitive rows.
allkeys=set().union(*(s.keys() for s in snapshots.values()))
identity={m for m in allkeys if m not in macros and any(s.get(m)!=base.get(m) for s in snapshots.values())}
# Include baseline identities even when shared by every alias of that CPU.
identity|={m for m in base if m.startswith('__tune_') or m in {'__k8','__k8__'}}
mo=provenance+'static const struct { const char *name, *value; x86_features required; } x86_feature_macros[] = {\n'
mo+=''.join('{'+json.dumps(m)+','+json.dumps(values[m])+','+mask(fs)+'},\n' for m,fs in sorted(macros.items()))+'};\n'
mo+='static const char *const x86_cpu_macro_names[] = {'+','.join(json.dumps(m) for m in sorted(identity))+'};\n'
mo+='static const struct { const char *cpu, *name, *value; } x86_cpu_macros[] = {\n'
for cpu,s in snapshots.items():
 for m in sorted(identity & s.keys()):mo+='{'+','.join(map(json.dumps,(cpu,m,s[m])))+'},\n'
mo+='};\n'
(ROOT/'src/lib/x86features-data.inc').write_text(out)
(ROOT/'src/driver/x86macros-data.inc').write_text(mo)
(ROOT/'bench/data/x86features-oracle.json').write_text(json.dumps({'version':version,'cli_features':sorted(cli_names),'attr_features':sorted(attr_names),'source_sha256':hashlib.sha256(source.encode()).hexdigest(),'cpus':list(snapshots),'feature_macros':{m:sorted(fs) for m,fs in macros.items()},'cpu_macro_names':sorted(identity)},indent=2,sort_keys=True)+'\n')
print(f'{len(cpus)} CPUs, {len(names)} features, {len(macros)} feature macros, {len(identity)} CPU macro names')
