#!/usr/bin/env python3
"""Emit X9 descriptors from pinned LLVM metadata and reviewed lowering maps.
Normal --check is offline and needs only Python and this checkout.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'ccs/vcc/arch/x64/intrinsics'
OUT = DATA.parent / 'intrinsics.inc'
SCALARS = {'void':'v', 'bool':'b', 'char':'c', 'signed char':'a', 'unsigned char':'C',
           'short':'s', 'signed short':'s', 'unsigned short':'S',
           'int':'i', 'signed int':'i', 'unsigned int':'I',
           'long int':'l', 'signed long int':'l', 'unsigned long int':'L',
           'long long int':'q', 'signed long long int':'q', 'unsigned long long int':'Q',
           'float':'f', 'double':'d', '_Float16':'h', '__bf16':'j', 'size_t':'z', 'uint64_t':'t'}
BITS = dict(v=0,b=8,c=8,a=8,C=8,s=16,S=16,i=32,I=32,l=64,L=64,q=64,Q=64,f=32,d=64,h=16,j=16,z=64,t=64)

def split_types(text):
    result, start, depth = [], 0, 0
    for i,c in enumerate(text):
        if c == '<': depth += 1
        elif c == '>': depth -= 1
        elif c == ',' and depth == 0:
            result.append(text[start:i].strip()); start = i+1
    if text[start:].strip(): result.append(text[start:].strip())
    return result

def encode_type(text):
    constant = '_Constant' in text
    text = ' '.join(text.replace('_Constant', '').split())
    vector = re.fullmatch(r'_Vector<\s*(\d+)\s*,\s*(.*?)\s*>', text)
    lanes = int(vector[1]) if vector else 0
    if vector: text = vector[2]
    pointer_count = text.count('*')
    const = bool(re.search(r'\bconst\b',text))
    text = ' '.join(text.replace('*',' ').replace('const',' ').split())
    scalar = SCALARS[text]
    token = ('V'+str(lanes) if lanes else '') + scalar
    # LLVM Prototype spelling puts qualifiers/pointers inside _Vector<...>;
    # BuiltinsEmitter applies them AFTER the aggregate (e.g V64cC*).
    if const: token = 'K' + token
    token = 'P'*pointer_count + token
    return ('!' if constant else '') + token, 0 if pointer_count else lanes*BITS[scalar]//8

def signature(prototype):
    ret,args=prototype.split('(',1)
    types=[ret]+split_types(args[:-1]); encoded=[encode_type(t) for t in types]
    return ' '.join(t for t,w in encoded), max(w for t,w in encoded)

def generate():
    metadata=json.loads((DATA/'builtins.json').read_text())
    mappings=json.loads((DATA/'lowerings.json').read_text())
    names={row['name'] for row in metadata['builtins']}
    assert set(mappings)<=names, sorted(set(mappings)-names)
    out=['/* Generated by bench/gen-x86-intrinsics.py; do not edit.\n',
         ' * Metadata: LLVM '+metadata['revision']+' (Apache-2.0 WITH LLVM-exception).\n',
         ' * Recognized descriptors are NOT a claim of target lowering support. */\n']
    for row in metadata['builtins']:
        name=row['name']; sig,width=signature(row['prototype']); m=mappings.get(name,{})
        cls=m.get('class','XI_UNSUPPORTED'); constraints=';'.join(':'.join(map(str,(c['argument'],c['min'],c['max']))) for c in row['ranges'])
        if cls!='XI_UNSUPPORTED':
            assert m.get('evidence'),name
            assert not row['special_validation'],name
        args=[name.removeprefix('__builtin_ia32_'),json.dumps(name),json.dumps(sig),json.dumps(row['features']),cls,json.dumps(m.get('mnemonic','')),json.dumps(m.get('order','')),str(width),json.dumps(constraints)]
        out.append('X86_INTRINSIC('+', '.join(args)+')\n')
    return ''.join(out)

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    text=generate()
    if args.check:
        if not OUT.exists() or OUT.read_text()!=text: raise SystemExit('intrinsics.inc is stale; run bench/gen-x86-intrinsics.py')
    else: OUT.write_text(text)
    elementwise=json.loads((DATA/'elementwise.json').read_text())
    lines=['/* Generated by bench/gen-x86-intrinsics.py; explicit reviewed integer overloads. */\n']
    for row in elementwise:
        fields=[row['op'],json.dumps(row['sig']),json.dumps(row['features']),row['class'],json.dumps(row['mnemonic']),json.dumps(row['order']),str(row['width'])]
        lines.append('X86_ELEMENTWISE('+', '.join(fields)+')\n')
    target=DATA.parent/'elementwise.inc';text2=''.join(lines)
    if args.check:
        if not target.exists() or target.read_text()!=text2: raise SystemExit('elementwise.inc is stale')
    else: target.write_text(text2)
    print(f'X9 descriptors: {text.count("X86_INTRINSIC(")} rows; '+('checked' if args.check else 'generated'))
if __name__=='__main__':main()
