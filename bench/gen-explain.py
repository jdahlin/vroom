#!/usr/bin/env python3
"""ccs/vcc/docs/diag/ID.md -> ccs/vcc/driver/explain.inc, the pages `vcc --explain ID` prints.

  bench/gen-explain.py [--check]

Each page becomes { "ID", "text" }, sorted by id (the driver searches the table); the
README and files that are not ID.md are left out.  --check fails when the table is out
of date.
"""
import os, re, sys

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = f'{R}/ccs/vcc/docs/diag'
OUT = f'{R}/ccs/vcc/driver/explain.inc'


def cstr(s):
    o = '"'
    for ch in s:
        if ch == '\\' or ch == '"':
            o += '\\' + ch
        elif ch == '\n':
            o += '\\n"\n\t"'
        elif ch == '\t':
            o += '\\t'
        elif ord(ch) < 0x20:
            o += '\\%03o' % ord(ch)
        else:
            o += ch
    return o + '"'


def pages():
    for f in sorted(os.listdir(DOCS)):
        m = re.fullmatch(r'([a-z]\w*)\.md', f)
        if m:
            yield m.group(1), open(os.path.join(DOCS, f), encoding='utf-8').read()


def render():
    out = ['/* generated by bench/gen-explain.py from ccs/vcc/docs/diag/ID.md: do not edit */']
    for i, t in pages():
        out.append(f'{{ "{i}",\n\t{cstr(t)} }},')
    return '\n'.join(out) + '\n'


def main():
    text = render()
    old = open(OUT).read() if os.path.exists(OUT) else None
    if '--check' in sys.argv:
        if old != text:
            print(f'gen-explain: {OUT} is out of date: run bench/gen-explain.py')
            return 1
        print(f'gen-explain: {sum(1 for _ in pages())} pages, up to date')
        return 0
    if old != text:
        open(OUT, 'w').write(text)
    print(f'{OUT}: {sum(1 for _ in pages())} pages')
    return 0


if __name__ == '__main__':
    sys.exit(main())
