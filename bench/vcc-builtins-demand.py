#!/usr/bin/env python3
"""Rank builtins by demand: which ones real code references, and what vcc does with them.

Scans the sources of the projects under work/ (the kernel, PostgreSQL, SQLite,
zlib, FFmpeg, Skia, nlohmann/json, TSVC, libc++'s headers) for __builtin_*,
__atomic_*, __sync_*, __c11_atomic_* and the x86/arm intrinsics (_mm*, NEON,
ACLE), skipping comments and string literals, maps each intrinsic to the
builtins that clang's own intrinsic headers call for it, classifies every name
with vcc (vpp, no clang), and writes doc/builtins-demand.md.

Classes (per name, best over aarch64-linux-gnu and x86_64-linux-gnu):
  consistent   in vcc's table and no line in consistency-failures.txt
  known        in vcc's table, with lines in consistency-failures.txt
  unchecked    implemented but outside the consistency check (special forms,
               unsuffixed __sync forms of a sized row, ...)
  stub         known to clang, vcc says "is not implemented"
  unknown      known to clang, vcc says "undeclared function"
  not-builtin  not a clang builtin name (a project's own identifier)

The report is regenerated by hand: its inputs are in work/ (git-ignored), not
in the checkout, so there is no --check.

Usage: bench/vcc-builtins-demand.py [--vpp PATH] [--work DIR] [-j N] [--out FILE]
"""
import argparse
import importlib.util
import os
import re
import sys
import time
from collections import Counter, defaultdict
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CLANG_INCLUDE = Path('/usr/lib/llvm-23/lib/clang/23/include')
LIBCXX = Path('/usr/lib/llvm-23/include/c++/v1')
OUT = ROOT / 'doc/builtins-demand.md'
EXTENSIONS = {'.c', '.h', '.cc', '.cpp', '.cxx', '.hpp', '.hh', '.hxx', '.inc', '.inl', '.S', '.def', '.ipp', ''}
SKIP_DIRS = {'.git', 'Documentation', 'doc', 'docs'}

# (name, directory under work or an absolute path, what it is)
PROJECTS = (
    ('linux', 'linux-allmod-src', 'the kernel tree (all architectures; work/linux is not in this checkout)'),
    ('postgresql', 'postgres', 'PostgreSQL'),
    ('sqlite', 'sqlite/sqlite-src-3500400', 'SQLite source tree'),
    ('zlib', 'zlib/zlib-1.4', 'zlib 1.4'),
    ('ffmpeg', 'ffmpeg-linux/ffmpeg-8.1.3', 'FFmpeg 8.1.3 (the C code; assembly is not scanned)'),
    ('skia', 'skia-src/skia', 'Skia, with its third_party'),
    ('nlohmann-json', 'cxx/json', 'nlohmann/json'),
    ('tsvc', 'testsuites/TSVC_2', 'TSVC_2 loops'),
    ('libc++', str(LIBCXX), 'libc++ headers of LLVM 23'),
)

CANDIDATE = re.compile(r'^(?:__builtin_\w+|__atomic_\w+|__sync_\w+|__c11_atomic_\w+|_mm\d*_\w+)$')
PREFILTER = re.compile(rb'__builtin_|__atomic_|__sync_|__c11_atomic|_mm\d*_|\bv[a-z0-9]+_[a-z]\d+|__arm_|__crc|__ldrex|__strex')
TOKEN = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\'|[A-Za-z_]\w*', re.S)
QUERY_WORDS = {'__has_builtin', '__has_constexpr_builtin', '__has_feature', '__has_attribute',
               '__has_include', '__has_extension', '__has_include_next'}


def load_consistency():
    spec = importlib.util.spec_from_file_location('consistency', ROOT / 'bench/vcc-builtins-consistency.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


# ----------------------------------------------------------------- lexical scan

def scan_text(text, wanted, counter):
    """count identifiers that are builtin-like or in `wanted`, outside comments and strings,
    and not the operand of __has_builtin and friends."""
    skip = False
    for match in TOKEN.finditer(text):
        token = match.group(0)
        first = token[0]
        if first == '/' or first == '"' or first == "'":
            continue
        if token in QUERY_WORDS:
            skip = True
            continue
        if skip:
            skip = False
            continue
        if token in wanted or CANDIDATE.match(token):
            counter[token] += 1


def scan_file(args):
    path, wanted = args
    try:
        data = Path(path).read_bytes()
    except OSError:
        return Counter()
    counter = Counter()
    if not PREFILTER.search(data):
        return counter
    scan_text(data.decode('latin-1'), wanted, counter)
    return counter


def source_files(directory):
    for base, dirs, files in os.walk(directory):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for name in files:
            if os.path.splitext(name)[1] in EXTENSIONS:
                yield os.path.join(base, name)


def scan_project(directory, wanted, jobs):
    total = Counter()
    files = Counter()
    count = 0
    with ProcessPoolExecutor(max_workers=jobs) as pool:
        for counter in pool.map(scan_file, ((p, wanted) for p in source_files(directory)), chunksize=64):
            count += 1
            total.update(counter)
            files.update(counter.keys())
    return total, files, count


# ------------------------------------------------- what the intrinsic headers need

def strip_comments(text):
    return re.sub(r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\\n])*"', lambda m: '\n' * m.group(0).count('\n') if m.group(0)[0] != '"' else '""', text, flags=re.S)


CODE_TOKEN = re.compile(r'[A-Za-z_]\w*|[(){};]')
SKIP_ATTR = {'__attribute__', '__declspec', '__aligned__', '__vector_size__', '__target__'}


def parse_header(text, table):
    """table[name] |= identifiers used by the function or macro `name`."""
    text = strip_comments(text).replace('\\\n', ' ')
    code = []
    for line in text.split('\n'):
        stripped = line.lstrip()
        if stripped.startswith('#'):
            match = re.match(r'#\s*define\s+([A-Za-z_]\w*)(.*)', stripped)
            if match:
                body = match.group(2)
                if body.startswith('('):
                    body = body[body.find(')') + 1:]
                table[match.group(1)] |= set(re.findall(r'[A-Za-z_]\w*', body))
            continue
        code.append(line)
    depth = 0
    paren = 0
    previous = None
    candidate = None
    current = None
    for match in CODE_TOKEN.finditer('\n'.join(code)):
        token = match.group(0)
        if token == '(':
            if depth == 0 and paren == 0 and previous and previous not in SKIP_ATTR:
                candidate = previous
            paren += 1
        elif token == ')':
            paren = max(0, paren - 1)
        elif token == '{':
            if depth == 0:
                current = candidate
            depth += 1
        elif token == '}':
            depth = max(0, depth - 1)
            if depth == 0:
                current = None
                candidate = None
        elif token == ';':
            if depth == 0:
                candidate = None
        else:
            if depth > 0 and current:
                table[current].add(token)
            previous = token
            continue
        previous = None if token in '(){};' else previous


def intrinsic_table():
    """(uses, header): identifier -> identifiers it uses, builtin -> first header that uses it."""
    uses = defaultdict(set)
    header_of = {}
    for path in sorted(CLANG_INCLUDE.glob('*.h')):
        local = defaultdict(set)
        parse_header(path.read_text(errors='replace'), local)
        for name, used in local.items():
            uses[name] |= used
            for ident in used:
                if ident.startswith('__builtin_'):
                    header_of.setdefault(ident, set()).add(path.name)
    return uses, header_of


def needed_builtins(name, uses, memo):
    """the __builtin_* names an intrinsic reaches, through other intrinsics (None: not in the headers)."""
    if name in memo:
        return memo[name]
    memo[name] = set()
    result = set()
    for ident in uses.get(name, ()):
        if ident.startswith('__builtin_'):
            result.add(ident)
        elif ident in uses and ident != name:
            result |= needed_builtins(ident, uses, memo)
    memo[name] = result
    return result


# ----------------------------------------------------------------- classification

def classify(consistency, vpp, names, clang_names):
    """{name: (class, detail)}"""
    rows = consistency.table_rows()
    samples, excluded = {}, {}
    for name in sorted(rows):
        sample, reason = consistency.build_sample(name, rows[name])
        if sample is None:
            excluded[name] = reason
    failing = defaultdict(set)
    _, _, observed = consistency.collect(vpp, rows, os.cpu_count() or 4, False)
    found = consistency.violations(sorted(set(rows) - set(excluded)), rows, observed)
    for invariant, name, tag in found:
        failing[name].add(invariant)
    result = {}
    unresolved = []
    for name in names:
        row_name = name
        if name not in rows and name + '_4' in rows:
            row_name = name + '_4'
        if row_name in rows:
            if row_name in excluded:
                result[name] = ('unchecked', 'special form: ' + excluded[row_name])
            elif failing[row_name]:
                result[name] = ('known', ', '.join(sorted(failing[row_name])))
            else:
                result[name] = ('consistent', '')
        elif name not in clang_names:
            result[name] = ('not-builtin', '')
        else:
            unresolved.append(name)
    best = {}
    for target in consistency.TARGETS:
        lines = {n: f'void t{i}(void) {{ {n}(); }}' for i, n in enumerate(unresolved)}
        outcome = consistency.probe(vpp, target, 'c', 0, 'syntax', lines)
        for name, (status, detail) in outcome.items():
            if status == 'ok' or ('not implemented' not in detail and 'undeclared' not in detail
                                  and 'implicit' not in detail):
                rank, value = 0, ('unchecked', 'accepted when called without arguments' if status == 'ok'
                                  else detail[:80])
            elif 'not implemented' in detail:
                rank, value = 1, ('stub', '')
            else:
                rank, value = 2, ('unknown', '')
            if name not in best or rank < best[name][0]:
                best[name] = (rank, value)
    for name in unresolved:
        result[name] = best[name][1]
    return result


FAMILY_HEADERS = (
    ('xmmintrin.h', 'x86 SSE'), ('emmintrin.h', 'x86 SSE2'), ('pmmintrin.h', 'x86 SSE3'),
    ('tmmintrin.h', 'x86 SSSE3'), ('smmintrin.h', 'x86 SSE4.1'), ('nmmintrin.h', 'x86 SSE4.2'),
    ('avx10', 'x86 AVX10'), ('avx512', 'x86 AVX-512'), ('ia32intrin', 'x86 ia32intrin (misc)'), ('avx2intrin.h', 'x86 AVX2'), ('avxintrin.h', 'x86 AVX'),
    ('immintrin.h', 'x86 AVX/BMI/misc'), ('bmi', 'x86 BMI'), ('crc', 'x86 CRC32'), ('f16c', 'x86 F16C'),
    ('fma', 'x86 FMA'), ('wmmintrin', 'x86 AES/PCLMUL'), ('adx', 'x86 ADX/carry'), ('adc', 'x86 ADX/carry'),
    ('rdseed', 'x86 RDRAND/RDSEED'), ('rdrand', 'x86 RDRAND/RDSEED'),
)
WORDS = (
    ('FP classification', re.compile(r'(isnan|isinf|isfinite|isnormal|fpclassify|signbit|isunordered|isgreater|isless|'
                                     r'nan|inf|huge_val|copysign|fabs|isfpclass)')),
    ('overflow arithmetic', re.compile(r'(add|sub|mul)\w*_overflow|addc|subc')),
    ('bit manipulation', re.compile(r'(clz|ctz|popcount|ffs|parity|bswap|bitreverse|rotate|clrsb|stdc_)')),
    ('memory and string', re.compile(r'(mem|str|wcs|wmem|alloca|object_size|dynamic_object)')),
    ('math library', re.compile(r'(sqrt|pow|exp|log|sin|cos|tan|floor|ceil|round|trunc|fma|fmod|fmin|fmax|'
                                r'hypot|cbrt|erf|gamma|rint|nearbyint|remainder|ldexp|frexp|modf|atan|asin|acos)')),
    ('control and assumptions', re.compile(r'(expect|unreachable|assume|trap|constant_p|choose_expr|'
                                           r'types_compatible|prefetch|speculation|debugtrap)')),
    ('va_list and frame', re.compile(r'(va_|frame_address|return_address|apply|setjmp|longjmp|unwind|eh_|stack)')),
)


def family(name, header_of):
    if name.startswith('__atomic_') or name.startswith('__sync_') or name.startswith('__c11_atomic_'):
        return 'atomics'
    if name.startswith('_mm'):
        return 'x86 (MS-style _mm builtin)'
    if name.startswith('__builtin_ia32_'):
        headers = sorted(header_of.get(name, ()))
        for key, label in FAMILY_HEADERS:
            if any(h.startswith(key) for h in headers):
                return label
        return 'x86 (header: %s)' % headers[0] if headers else 'x86 (no clang header)'
    if name.startswith('__builtin_neon_'):
        return 'arm NEON'
    if name.startswith('__builtin_arm_') or name.startswith('__builtin_aarch64_'):
        return 'arm ACLE/system'
    if name.startswith('__builtin_sve_') or name.startswith('__builtin_sme_'):
        return 'arm SVE/SME'
    for label, pattern in WORDS:
        if pattern.search(name):
            return label
    return 'other'


# ----------------------------------------------------------------------- report

def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--vpp', type=Path, default=None)
    parser.add_argument('--work', type=Path, default=None)
    parser.add_argument('-j', '--jobs', type=int, default=os.cpu_count() or 4)
    parser.add_argument('--out', type=Path, default=OUT)
    args = parser.parse_args()
    consistency = load_consistency()
    vpp = (args.vpp or Path(os.environ.get('VCC_BIN') or ROOT / 'build/linux/src') / 'vpp').resolve()
    work = args.work or (ROOT / 'work' if (ROOT / 'work').is_dir() else Path('/source/vroom/work'))
    start = time.time()

    uses, header_of = intrinsic_table()
    intrinsic_names = {n for n in uses if re.match(r'^_mm\d*_\w+$', n)}
    # NEON/ACLE intrinsics: functions of clang's arm headers that call a builtin
    for header in ('arm_neon.h', 'arm_acle.h', 'arm_fp16.h', 'arm_bf16.h'):
        path = CLANG_INCLUDE / header
        local = defaultdict(set)
        parse_header(path.read_text(errors='replace'), local)
        intrinsic_names |= {n for n, used in local.items() if any(u.startswith('__builtin_') for u in used)}
    wanted = frozenset(intrinsic_names)

    counts, file_counts, scanned = {}, {}, {}
    missing = []
    for name, directory, _ in PROJECTS:
        path = Path(directory)
        if not path.is_absolute():
            path = work / directory
        if not path.is_dir():
            missing.append((name, str(path)))
            continue
        counts[name], file_counts[name], scanned[name] = scan_project(path, wanted, args.jobs)
    projects = [p for p in PROJECTS if p[0] in counts]

    clang_names, _ = consistency_candidates()
    memo = {}
    # demand: direct references, and references through an intrinsic
    direct = defaultdict(Counter)
    via = defaultdict(Counter)
    intrinsics_used = defaultdict(Counter)
    for project, counter in counts.items():
        for ident, count in counter.items():
            if ident in wanted:
                intrinsics_used[project][ident] = count
                for builtin in needed_builtins(ident, uses, memo):
                    via[project][builtin] += count
            elif ident.startswith('__builtin_') or '_atomic_' in ident or ident.startswith('__sync_'):
                direct[project][ident] += count
            elif ident not in wanted:
                direct[project][ident] += count
    names = set()
    for project in counts:
        names |= set(direct[project]) | set(via[project])
    klass = classify(consistency, vpp, sorted(names), clang_names)

    def demand(name):
        projects_with = [p for p in counts if direct[p][name] or via[p][name]]
        refs = sum(direct[p][name] + via[p][name] for p in counts)
        return len(projects_with), refs

    lines = []
    out = lines.append
    out('# Builtin demand')
    out('')
    out('Generated by `bench/vcc-builtins-demand.py` (`--out`); **regenerated by hand**: its inputs are the '
        'project trees under `work/` (git-ignored) and LLVM 23 in `/usr/lib/llvm-23`, which a checkout does '
        'not have, so no `--check` verifies that this file is current.  No compiler code is involved: the '
        'classes below are what `vpp` says today.  See doc/PLAN-builtins.md, "Demand".')
    out('')
    out('## Method')
    out('')
    out('- Scan: every `__builtin_*`, `__atomic_*`, `__sync_*`, `__c11_atomic_*` identifier and every x86 '
        '(`_mm*`), NEON and ACLE intrinsic in the projects\' `%s` files, outside comments and string '
        'literals (a regular-expression tokenizer, not vcc\'s lexer), not as the operand of `__has_builtin` '
        'and friends.  Code under `#if 0` or for another target is counted (the scan has no preprocessor); '
        'the directories `Documentation`, `doc`, `docs` and `.git` are skipped.' % ' '.join(
            sorted(e for e in EXTENSIONS if e)))
    out('- An intrinsic counts for the builtins clang\'s own header (`%s`) calls for it, transitively through '
        'other intrinsics: a reference to `_mm_add_epi8` is a reference to what `emmintrin.h` needs.  '
        '"refs" is direct references plus those.  An intrinsic that needs no builtin (plain vector '
        'operators) does not appear.' % CLANG_INCLUDE)
    out('- Classes, per name, best over aarch64-linux-gnu and x86_64-linux-gnu: `consistent` (in vcc\'s '
        'table, no line in `src/test/builtins/consistency-failures.txt`), `known` (in the table, with lines '
        'there: the invariants are listed), `unchecked` (implemented, outside the consistency check: special '
        'forms, the unsuffixed `__sync_*` forms, ...), `stub` (clang knows it, vcc answers "is not '
        'implemented"), `unknown` (clang knows it, vcc answers "undeclared function"), `not-builtin` '
        '(not a clang builtin: a project\'s own `__atomic_foo`, left out of the tables).')
    out('- `known` is not one level: `constexpr-claimed-not-folded` lines are benign (clang does not fold '
        'those calls either); `not-compiled`, `c-only-callable`, `claimed-not-callable` and `crash` are the '
        'ones that block a build.  A name valid on one target only (`__builtin_ia32_*` on arm64) is judged '
        'by the table, which has no target; a name the table lacks, by the better of the two probes.')
    out('')
    out('## Projects')
    out('')
    out('| project | files read | what |')
    out('| --- | ---: | --- |')
    for name, _, what in projects:
        out(f'| {name} | {scanned[name]} | {what} |')
    out('')
    if missing:
        out('Not scanned (directory absent): ' + ', '.join(f'{n} (`{p}`)' for n, p in missing) + '.')
        out('')
    out('Not scanned on purpose: clang\'s own intrinsic headers (the provider, used above for the mapping) '
        'and `work/testsuites/llvm` (clang\'s tests, not code anyone runs).')
    out('')

    order = ('consistent', 'known', 'unchecked', 'stub', 'unknown')

    def project_names(project):
        found = (set(direct[project]) | set(via[project]))
        return {n for n in found if klass[n][0] != 'not-builtin'}

    out('## Summary')
    out('')
    out('Distinct builtins a project references (directly or through an intrinsic), by class; intrinsics '
        'are the distinct `_mm`/NEON/ACLE names it uses, and how many of them need a builtin that is not '
        '`consistent`.')
    out('')
    out('| project | builtins | ' + ' | '.join(order) + ' | not-builtin | intrinsics | intrinsics blocked |')
    out('| --- | ---: | ' + ' | '.join('---:' for _ in order) + ' | ---: | ---: | ---: |')
    totals = Counter()
    for name, _, _ in projects:
        found = project_names(name)
        tally = Counter(klass[n][0] for n in found)
        other = len({n for n in set(direct[name]) | set(via[name]) if klass[n][0] == 'not-builtin'})
        blocked = 0
        for intrinsic in intrinsics_used[name]:
            if any(klass[b][0] != 'consistent' for b in needed_builtins(intrinsic, uses, memo) if b in klass):
                blocked += 1
        out(f'| {name} | {len(found)} | ' + ' | '.join(str(tally[c]) for c in order) +
            f' | {other} | {len(intrinsics_used[name])} | {blocked} |')
    union = set()
    for name, _, _ in projects:
        union |= project_names(name)
    tally = Counter(klass[n][0] for n in union)
    out(f'| **all (distinct)** | {len(union)} | ' + ' | '.join(str(tally[c]) for c in order) + ' | | | |')
    out('')

    def blocking(name):
        cls, detail = klass[name]
        if cls in ('stub', 'unknown'):
            return True
        if cls == 'known':
            return bool(set(detail.split(', ')) - {'constexpr-claimed-not-folded', 'constexpr-folds-unclaimed',
                                                    'fold-c-only', 'fold-cxx-only'})
        return False

    ranked = sorted((n for n in union if blocking(n)), key=lambda n: (-demand(n)[0], -demand(n)[1], n))
    out('## Next 30')
    out('')
    out('The highest-demand names that are `stub`, `unknown` or `known` with a failure that blocks a build '
        '(not only a fold difference), by number of projects then references; grouped by family below.  '
        'The family of an x86 builtin is the earliest ISA level (SSE ... AVX-512) of the headers that use it.  Demand through clang\'s '
        '`arm_neon.h` and x86 headers exists only where the compiled code includes those headers: vcc has its '
        'own `<arm_neon.h>` (`src/headers`), so the `__builtin_neon_*` stubs matter only for clang\'s header.')
    out('')
    top = ranked[:30]
    groups = defaultdict(list)
    for n in top:
        groups[family(n, header_of)].append(n)
    out('| # | builtin | class | projects | refs | family | detail |')
    out('| ---: | --- | --- | ---: | ---: | --- | --- |')
    for index, n in enumerate(top, 1):
        p, r = demand(n)
        out(f'| {index} | `{n}` | {klass[n][0]} | {p} | {r} | {family(n, header_of)} | {klass[n][1]} |')
    out('')
    for label in sorted(groups, key=lambda g: -len(groups[g])):
        out(f'- **{label}** ({len(groups[label])}): ' + ', '.join(f'`{n}`' for n in groups[label]))
    out('')
    out('All blocking names by family (every project; count of names, references):')
    out('')
    families = defaultdict(list)
    for n in ranked:
        families[family(n, header_of)].append(n)
    out('| family | names | refs | stub | unknown | known |')
    out('| --- | ---: | ---: | ---: | ---: | ---: |')
    for label in sorted(families, key=lambda g: -sum(demand(n)[1] for n in families[g])):
        members = families[label]
        kinds = Counter(klass[n][0] for n in members)
        out(f'| {label} | {len(members)} | {sum(demand(n)[1] for n in members)} | {kinds["stub"]} | '
            f'{kinds["unknown"]} | {kinds["known"]} |')
    out('')

    out('## Per project')
    out('')
    out('Every referenced builtin that is not `consistent`, ranked by the number of projects that '
        'reference it, then by references in this project.  `known` lines give the invariants.')
    out('')
    for name, _, _ in projects:
        rows = [n for n in project_names(name) if klass[n][0] != 'consistent']
        rows.sort(key=lambda n: (-demand(n)[0], -(direct[name][n] + via[name][n]), n))
        out(f'### {name}')
        out('')
        out(f'{len(rows)} of {len(project_names(name))} referenced builtins are not `consistent`.')
        out('')
        if not rows:
            continue
        out('| builtin | class | projects | refs here (direct+intrinsic) | detail |')
        out('| --- | --- | ---: | ---: | --- |')
        for n in rows:
            out(f'| `{n}` | {klass[n][0]} | {demand(n)[0]} | {direct[name][n]}+{via[name][n]} | {klass[n][1]} |')
        out('')

    out('## Intrinsics and the builtins they need')
    out('')
    out('Intrinsics the projects use that need at least one builtin (clang\'s header, transitive), with '
        'the class of each builtin; those whose builtins are all `consistent` are counted only.')
    out('')
    all_intrinsics = Counter()
    for project in counts:
        all_intrinsics.update(intrinsics_used[project])
    fine = 0
    out('| intrinsic | projects | refs | builtins (class) |')
    out('| --- | ---: | ---: | --- |')
    for intrinsic, refs in sorted(all_intrinsics.items(), key=lambda kv: (-sum(1 for p in counts if intrinsics_used[p][kv[0]]), -kv[1], kv[0])):
        builtins = sorted(needed_builtins(intrinsic, uses, memo))
        if all(klass.get(b, ('consistent',))[0] == 'consistent' for b in builtins):
            fine += 1
            continue
        bad = [b for b in builtins if klass.get(b, ('consistent',))[0] != 'consistent']
        out(f'| `{intrinsic}` | {sum(1 for p in counts if intrinsics_used[p][intrinsic])} | {refs} | ' +
            ', '.join(f'`{b}` ({klass[b][0]})' for b in bad) + ' |')
    out('')
    out(f'{fine} further intrinsics need only `consistent` builtins (or none).')
    out('')
    args.out.write_text('\n'.join(lines))
    print(f'{args.out}: {len(union)} builtins, {len(counts)} projects, {time.time() - start:.0f} s')
    return 0


