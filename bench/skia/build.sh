#!/bin/bash
# Skia (work/skia-src/skia: git clone https://skia.googlesource.com/skia.git) built by vcc alone:
# vpp -c compiles, vlink links (clang is asked only for its link line: -### runs nothing), var archives
# (through a private vccd).  CPU backend only; PNG/JPEG/WebP/expat/fontconfig/FreeType off unless
# SKIA_SYSTEM_LIBS=1 (needs libpng-dev libjpeg-dev libwebp-dev libfreetype-dev libfontconfig-dev
# libexpat1-dev).  Reports the failed steps and how many function definitions got code.
#
#   bench/skia/build.sh [--clean]          VCC_BIN=DIR: the tools (default build/linux/src)
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
MAIN=$ROOT; case $ROOT in */.claude/worktrees/*) MAIN=${ROOT%%/.claude/worktrees/*} ;; esac
SKIA=${SKIA:-$MAIN/work/skia-src/skia}
B=${VCC_BIN:-$ROOT/build/linux/src}
D=$SKIA/../vcc-bin
CLANG=${CLANG:-$(command -v clang-23 || command -v clang)}
CLANGXX=${CLANGXX:-$(command -v clang++-23 || command -v clang++)}
[ -d "$SKIA" ] || { echo "no $SKIA (git clone https://skia.googlesource.com/skia.git)"; exit 1; }
mkdir -p "$D"
[ -x "$SKIA/bin/gn" ] || python3 "$SKIA/bin/fetch-gn"
[ -x "$SKIA/third_party/ninja/ninja" ] || python3 "$SKIA/bin/fetch-ninja"

for L in cc cxx; do
    DRV=$CLANG; [ $L = cxx ] && DRV=$CLANGXX
    cat > "$D/vcc-$L" <<W
#!/bin/bash
# generated by bench/skia/build.sh: compile with vpp, link with vlink (clang -### only for the line)
B=$B
[ "\$1" = --version ] && VCC_SOCK=$D/vccd.sock exec "\$B/vcc" --version
case " \$* " in
*" -c "*) exec "\$B/vpp" "\$@" ;;
esac
line=\$($DRV -### "\$@" 2>&1 | tail -1)
eval "set -- \$line"
shift
exec "\$B/vlink" "\$@"
W
done
printf '#!/bin/sh\nVCC_SOCK=%s/vccd.sock exec %s/var "$@"\n' "$D" "$B" > "$D/vcc-ar"
chmod +x "$D"/vcc-cc "$D"/vcc-cxx "$D"/vcc-ar

ARGS="cc=\"$D/vcc-cc\" cxx=\"$D/vcc-cxx\" ar=\"$D/vcc-ar\" is_official_build=true is_debug=false
 skia_use_partition_alloc=false skia_enable_ganesh=false skia_enable_graphite=false skia_use_vulkan=false
 skia_use_gl=false skia_enable_pdf=false skia_use_icu=false skia_enable_skottie=false skia_use_dng_sdk=false
 skia_use_piex=false skia_use_wuffs=false extra_cflags_cc=[\"-stdlib=libc++\"] extra_ldflags=[\"-stdlib=libc++\"]"
[ "${SKIA_SYSTEM_LIBS:-}" = 1 ] || ARGS="$ARGS skia_use_libpng_decode=false skia_use_libpng_encode=false
 skia_use_libjpeg_turbo_decode=false skia_use_libjpeg_turbo_encode=false skia_use_libwebp_decode=false
 skia_use_libwebp_encode=false skia_use_expat=false skia_use_fontconfig=false skia_use_freetype=false
 skia_enable_fontmgr_empty=true skia_enable_svg=false"

# a private vccd of these tools (a shim refuses a server of another build)
pkill -f "vccd --sock $D/vccd.sock" 2>/dev/null || true
rm -f "$D/vccd.sock"
"$B/vccd" --sock "$D/vccd.sock" -j 6 > "$D/vccd.log" 2>&1 &
VPID=$!
trap 'kill $VPID 2>/dev/null || true' EXIT
for _ in $(seq 100); do [ -S "$D/vccd.sock" ] && break; sleep 0.05; done

cd "$SKIA"
bin/gn gen out/vcc --args="$ARGS" > /dev/null
[ "${1:-}" = --clean ] && third_party/ninja/ninja -C out/vcc -t clean > /dev/null
t0=$(date +%s.%N)
third_party/ninja/ninja -C out/vcc -k 0 -j 6 > "$D/build.log" 2>&1 || true
t1=$(date +%s.%N)
printf 'build: %.1f s, %d failed (log %s)\n' "$(echo "$t1 - $t0" | bc)" "$(grep -c '^FAILED' "$D/build.log" || true)" "$D/build.log"
grep '^FAILED' "$D/build.log" | head -20 || true
echo "objects: $(find out/vcc/obj -name '*.o' | wc -l); libraries: $(cd out/vcc && ls *.a 2>/dev/null | tr '\n' ' ')"

# how many function definitions got code (vcc leaves out a function it cannot build yet)
cd out/vcc
../../third_party/ninja/ninja -t commands | grep "$D/vcc-cxx .* -c " | sed 's| -o [^ ]*| -o /dev/null|; s| -MD -MF [^ ]*||' |
    tr '\n' '\0' | xargs -0 -P 6 -I{} sh -c 'VCC_CXX_PROGRESS=1 {} 2>&1 | grep -o "function definitions [0-9]*, with code [0-9]*"' |
    awk '{d+=$3; w+=$6; if ($3==$6) f++; n++} END {printf "code: %d of %d function definitions (%.1f%%), %d of %d TUs complete\n", w, d, d ? 100*w/d : 0, f, n}'
