#!/usr/bin/env python3
"""
ccs/vcc/emit/walk/prefix.h: the walker's function names, for compiling emit/walk/*.c
a second time under other names (PLAN-vir.md V2, SPEC-vir.md X1).

The walker is one source for every CPU: its own functions are wk_*, the target
is reached through LO(name).  A second instantiation (the VIR builder: LO
-> vir_, the walker's own names -> vir_wk_...) is one more translation unit
that defines WK_PREFIX and LO_PREFIX and includes the walker files.  When
WK_PREFIX is defined, prefix.h renames every function the walker defines;
when it is not, the header is empty and nothing changes.

The list is taken from the walker's own function definitions (a function at
file scope in walk/*.c, VPRIV or static, named wk_*), so it cannot go stale
silently: --check fails if the checked-in header differs, if a wk_* function
declared in walk.h is not defined in walk/*.c (it would be renamed but not
found), or if walk/*.c calls a name that LO() should have made (x64_*).

  bench/gen-walkprefix.py           regenerate ccs/vcc/emit/walk/prefix.h
  bench/gen-walkprefix.py --check   exit 1 if it is out of date or inconsistent
"""
import glob, os, re, sys

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = f'{R}/ccs/vcc/emit/walk'
OUT = f'{D}/prefix.h'

DEF = re.compile(r'^(?:VPRIV|static)\b[^();=]*?\b(wk_\w+)\s*\(', re.M)


def defined():
    names = {}
    for f in sorted(glob.glob(f'{D}/*.c')):
        src = open(f).read()
        for m in DEF.finditer(src):
            # a definition has its body after the closing parenthesis; a
            # prototype ends in ';' (skip those)
            i, depth = m.end(), 1
            while depth:
                depth += (src[i] == '(') - (src[i] == ')')
                i += 1
            if src[i:].lstrip().startswith('{'):
                names.setdefault(m.group(1), os.path.basename(f))
    return names


def generate(names):
    out = ['/* Generated by bench/gen-walkprefix.py from the function definitions in the walker sources; do not edit.',
           ' * Included by walk.h.  With WK_PREFIX defined (a second instantiation of the walker, which',
           ' * also defines LO_PREFIX) every function the walker defines gets that prefix; without it',
           ' * this header is empty. */',
           '#ifndef VCC_WALK_PREFIX_H',
           '#define VCC_WALK_PREFIX_H',
           '#ifdef WK_PREFIX',
           '#define WK_PASTE_(p, n) p##n',
           '#define WK_PASTE(p, n) WK_PASTE_(p, n)',	# (the extra level expands WK_PREFIX first)
           '#define WK_NAME(n) WK_PASTE(WK_PREFIX, n)']
    for n in sorted(names):
        out.append(f'#define {n} WK_NAME({n})')
    out += ['#endif', '#endif', '']
    return '\n'.join(out)


def main():
    names = defined()
    bad = []
    hdr = open(f'{D}/walk.h').read()
    for n in sorted(set(re.findall(r'\b(wk_\w+)\s*\(', hdr))):
        if n not in names:
            bad.append(f'{n}: declared in walk.h, not defined in walk/*.c')
    for f in sorted(glob.glob(f'{D}/*.c')):
        for i, line in enumerate(open(f), 1):
            if re.search(r'\bx64_\w+', line) and 'LO(' not in line:
                bad.append(f'{os.path.basename(f)}:{i}: a target name outside LO(): {line.strip()}')
    text = generate(names)
    if '--check' in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ''
        if cur != text:
            bad.append(f'{OUT} is out of date: run bench/gen-walkprefix.py')
        for b in bad:
            print(b, file=sys.stderr)
        print(f'walkprefix: {len(names)} names' + ('' if not bad else f', {len(bad)} problems'))
        sys.exit(1 if bad else 0)
    for b in bad:
        print('warning:', b, file=sys.stderr)
    open(OUT, 'w').write(text)
    print(f'{OUT}: {len(names)} names')


main()
