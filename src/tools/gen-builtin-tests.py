#!/usr/bin/env python3
"""Generate shared integer builtin tests with independently computed answers."""

import argparse
from pathlib import Path
import re

SRC = Path(__file__).resolve().parents[1]
OUTPUT = SRC / 'test/vcc/generated_builtin_scalars.c'
ROW = re.compile(r'INTEGER_BUILTIN\("__builtin_(\w+)", CC_BUILTIN_\w+, [01], "([A-Za-z]+)", (\w+)\)')
TYPES = {
    'C': ('unsigned char', 8),
    'h': ('unsigned short', 16),
    'u': ('unsigned int', 32),
    'i': ('int', 32),
    'L': ('unsigned long', None),
    'l': ('long', None),
    'W': ('unsigned long long', 64),
    'w': ('long long', 64),
}


def result(family, value, width, count):
    if family == 'bswap':
        return int.from_bytes(value.to_bytes(width // 8, 'little'), 'big')
    if family == 'bitreverse':
        return int(f'{value:0{width}b}'[::-1], 2)
    if family == 'popcount':
        return value.bit_count()
    if family == 'parity':
        return value.bit_count() % 2
    if family == 'clz':
        return width - value.bit_length()
    if family == 'ctz':
        return (value & -value).bit_length() - 1
    if family == 'clrsb':
        sign = value >> (width - 1)
        magnitude = value ^ ((1 << width) - 1) if sign else value
        return width - 1 - magnitude.bit_length()
    if family in ('rotate_left', 'rotate_right'):
        shift = (count if family == 'rotate_left' else -count) % width
        mask = (1 << width) - 1
        return ((value << shift) | (value >> (width - shift))) & mask
    raise ValueError(f'unknown builtin family {family}')


def literal(value):
    return f'0x{value:x}ull'


def test_cases(name, signature, family, width):
    operand_type = TYPES[signature[1]][0]
    rotations = len(signature) == 3
    mask = (1 << width) - 1
    values = (0, 1, 1 << (width - 1), mask, 0x8912345678abcdef & mask)
    counts = (0, width, width + 1, width - 1, 3)
    lines = []
    for index, (value, count) in enumerate(zip(values, counts)):
        if not value and family in ('clz', 'ctz'):
            continue
        answer = literal(result(family, value, width, count))
        arg = f'({operand_type}){literal(value)}'
        constant_count = f', ({operand_type}){count}' if rotations else ''
        runtime_count = f', count_{index}' if rotations else ''
        lines.append(f'    STATIC_ASSERT(__builtin_{name}({arg}{constant_count}) == {answer},'
                     f' "{name} constant case {index}");')
        lines.append(f'    volatile {operand_type} value_{index} = {arg};')
        if rotations:
            lines.append(f'    volatile {operand_type} count_{index} = {count};')
        lines.append(f'    if (__builtin_{name}(value_{index}{runtime_count}) != {answer})'
                     f' return {index + 1};')
    return lines


def registry_rows(registry):
    rows = []
    for line in registry.read_text().splitlines():
        if line.startswith('INTEGER_BUILTIN'):
            match = ROW.fullmatch(line)
            if not match:
                raise ValueError(f'invalid builtin registry row: {line}')
            rows.append(match.groups())
    return rows


def invalid_arity(registry):
    for name, signature, _ in registry_rows(registry):
        for count in (len(signature) - 2, len(signature)):
            args = ', '.join('1' for _ in range(count))
            yield f'void bad_{name}_{count}(void) {{ (void)__builtin_{name}({args}); }}'


def generate(registry):
    rows = registry_rows(registry)
    lines = [
        '/* Generated by src/tools/gen-builtin-tests.py. */',
        '',
        '#ifdef __cplusplus',
        '#define STATIC_ASSERT static_assert',
        '#else',
        '#define STATIC_ASSERT _Static_assert',
        '#if defined(__aarch64__) && __has_builtin(__builtin_ia32_crc32qi)',
        '#error x86 builtin advertised on arm64',
        '#endif',
        '#if defined(__x86_64__) && __has_builtin(__builtin_arm_dmb)',
        '#error arm builtin advertised on x86-64',
        '#endif',
        '#endif',
        '',
    ]
    for name, signature, family in rows:
        lines.extend([f'static int test_{name}(void)', '{'])
        _, width = TYPES[signature[1]]
        if width is None:
            lines.extend(['#if __SIZEOF_LONG__ == 8', *test_cases(name, signature, family, 64),
                          '#else', *test_cases(name, signature, family, 32), '#endif'])
        else:
            lines.extend(test_cases(name, signature, family, width))
        lines.extend(['    return 0;', '}', ''])
    lines.extend(['#undef STATIC_ASSERT', '', 'int main(void)', '{'])
    for index, (name, _, _) in enumerate(rows):
        lines.append(f'    if (test_{name}()) return {index + 1};')
    lines.extend(['    return 0;', '}', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group()
    action.add_argument('--check', action='store_true')
    action.add_argument('--invalid-arity', action='store_true',
                        help='print one too-few and one too-many call per registry row')
    parser.add_argument('--registry', type=Path,
                        default=SRC.parent / 'build/linux/src/generated/include/frontend/integer-builtins.inc')
    args = parser.parse_args()
    if args.invalid_arity:
        print('\n'.join(invalid_arity(args.registry)))
        return
    generated = generate(args.registry)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            parser.exit(1, 'Run src/tools/gen-builtin-tests.py to refresh builtin tests\n')
    else:
        OUTPUT.write_text(generated)


if __name__ == '__main__':
    main()
