#!/usr/bin/env python3
"""Generate portable scalar builtin tests with independently computed answers."""

import argparse
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[1] / 'test/vcc/generated_builtin_scalars.c'


def byte_swap(value, width):
    return int.from_bytes(value.to_bytes(width // 8, 'little'), 'big')


def popcount(value, _width):
    return value.bit_count()


def literal(value):
    return f'0x{value:x}ull'


def generate():
    families = (
        (byte_swap, (
            ('bswap16', 'unsigned short', 16),
            ('bswap32', 'unsigned int', 32),
            ('bswap64', 'unsigned long long', 64),
        )),
        (popcount, (
            ('popcount', 'unsigned int', 32),
            ('popcountll', 'unsigned long long', 64),
        )),
    )
    lines = [
        '/* Generated by src/tools/gen-builtin-tests.py. */',
        '',
        '#if defined(__aarch64__) && __has_builtin(__builtin_ia32_crc32qi)',
        '#error x86 builtin advertised on arm64',
        '#endif',
        '#if defined(__x86_64__) && __has_builtin(__builtin_arm_dmb)',
        '#error arm builtin advertised on x86-64',
        '#endif',
        '',
    ]
    runtime = []
    for evaluate, variants in families:
        for name, operand_type, width in variants:
            builtin = f'__builtin_{name}'
            mask = (1 << width) - 1
            inputs = (0, 1, 1 << (width - 1), mask, 0x8912345678abcdef & mask)
            lines.append(f'static volatile {operand_type} {name}_inputs[] = {{')
            lines.extend(f'    {literal(value)},' for value in inputs)
            lines.append('};')
            for index, value in enumerate(inputs):
                answer = literal(evaluate(value, width))
                lines.append(
                    f'_Static_assert({builtin}(({operand_type}){literal(value)}) == {answer},'
                )
                lines.append(f'               "{name} constant case {index}");')
                runtime.extend([
                    f'    if ({builtin}({name}_inputs[{index}]) != {answer})',
                    f'        return {len(runtime) // 2 + 1};',
                ])
            lines.append('')
    return '\n'.join([*lines, 'int main(void)', '{', *runtime, '    return 0;', '}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            parser.exit(1, 'Run src/tools/gen-builtin-tests.py to refresh builtin tests\n')
    else:
        OUTPUT.write_text(generated)


if __name__ == '__main__':
    main()
