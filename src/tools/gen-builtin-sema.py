#!/usr/bin/env python3
"""Generate C builtin table rows and custom semantic dispatch from family files."""

import argparse
from pathlib import Path
import re

FRONTEND = Path(__file__).resolve().parents[1] / "frontend" / "c"
OUTPUT = FRONTEND / "builtin-sema.inc"
RECORD = re.compile(
    r'C_BUILTIN_SEMA\("(__builtin_\w+)", (CC_BUILTIN_\w+), ([01]), '
    r'"([a-zA-Z.]+)", (cc_builtin_\w+)\)'
)


def generate():
    records = []
    names = set()
    handlers = {}
    for path in sorted(FRONTEND.glob("builtin-*.cpp")):
        for number, line in enumerate(path.read_text().splitlines(), 1):
            line = line.strip()
            if not line.startswith("C_BUILTIN_SEMA("):
                continue
            match = RECORD.fullmatch(line)
            if not match:
                raise SystemExit(f"{path}:{number}: invalid C_BUILTIN_SEMA record")
            name, id_, flags, signature, handler = match.groups()
            if name in names or handlers.get(id_, handler) != handler:
                raise SystemExit(f"{path}:{number}: conflicting builtin registration")
            names.add(name)
            handlers[id_] = handler
            records.append(f'    {{"{name}", {id_}, {flags}, "{signature}"}},')
    cases = []
    for id_, handler in handlers.items():
        cases.extend([f"    case {id_}:", f"        return {handler}(c, b->id, loc);"])
    return "\n".join([
        "/* Generated by src/tools/gen-builtin-sema.py. */",
        "#ifdef C_BUILTIN_SEMA_TABLE",
        *records,
        "#else",
        *cases,
        "#endif",
        "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            parser.exit(1, "Run src/tools/gen-builtin-sema.py to update builtin-sema.inc\n")
    else:
        OUTPUT.write_text(generated)


if __name__ == "__main__":
    main()
