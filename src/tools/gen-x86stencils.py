#!/usr/bin/env python3
"""Generate the machine-code stencils of the x86 builtins.

For each __builtin_ia32_* that clang's intrinsic headers use and vcc has no
node or instruction for, clang compiles

    void stencil(char *p) { *(R *)p = builtin(*(T0 *)(p + 16), ...); }

with only the builtin's features, and the function's bytes (its final ret
left off) become vcc's expansion of the builtin: operands and result in one
frame block, the block's address in rdi.  A builtin with constant operands
has a stencil per value.  The outputs are checked in (clang runs only here):

    src/include/frontend/x86-stencil-names.inc   spelling, signature (front ends)
    src/arch/x64/codegen/x86-stencils.inc        features, variants, code
"""

import concurrent.futures
import glob
import importlib.util
import itertools
import json
from pathlib import Path
import re
import struct
import subprocess
import sys
import tempfile

SRC = Path(__file__).resolve().parents[1]
NAMES = SRC / 'include/frontend/x86-stencil-names.inc'
CODE = SRC / 'arch/x64/codegen/x86-stencils.inc'
GENERATED = '/* Generated by src/tools/gen-x86stencils.py. */'
CLANG = 'clang'
OBJDUMP = 'llvm-objdump-23'

spec = importlib.util.spec_from_file_location(
    'registrations', SRC / 'tools/gen-builtin-registrations.py')
registrations = importlib.util.module_from_spec(spec)
sys.modules['registrations'] = registrations
spec.loader.exec_module(registrations)

# element type: signature letter (cc_builtin_signature_type), size
ELEMENTS = {
    'char': ('c', 1), 'signed char': ('c', 1), 'unsigned char': ('C', 1),
    'short': ('N', 2), 'signed short': ('N', 2), 'unsigned short': ('h', 2),
    'int': ('i', 4), 'signed int': ('i', 4), 'unsigned int': ('u', 4),
    'long int': ('l', 8), 'unsigned long int': ('L', 8),
    'long long int': ('w', 8), 'signed long long int': ('w', 8),
    'unsigned long long int': ('W', 8), 'size_t': ('L', 8),
    'uint64_t': ('L', 8), 'float': ('f', 4), 'double': ('d', 8),
    '_Float16': ('x', 2), '__bf16': ('g', 2),
}
VECTOR_BYTES = {8: '3', 16: '4', 32: '5', 64: '6'}


# clang 23 folds a memory operand into these with the wrong operand order
# (a*c+b for a*b+c): their operands are read as volatile, which keeps them in
# registers
UNFOLDED = {'__builtin_ia32_vfmaddsd3_maskz', '__builtin_ia32_vfmaddss3_maskz'}


class Skip(Exception):
    pass


class Type:
    """a prototype's type: its signature code, C spelling and size"""

    def __init__(self, text):
        text = ' '.join(text.replace('*', ' * ').split())
        pointers = []
        while text.endswith('*'):
            text = text[:-1].strip()
            pointers.append('*')
        vector = re.fullmatch(r'_(?:Ext)?Vector<\s*(\d+)\s*,\s*(.*?)\s*>', text)
        lanes = 0
        if vector:
            lanes, text = int(vector[1]), vector[2]
            while text.endswith('*'):
                text = text[:-1].strip()
                pointers.append('*')
        constant = False
        if text.endswith(' const'):
            text, constant = text[:-6], True
        if text == 'void' and not lanes:
            code, spelling, size = 'v', 'void', 0
        elif text in ELEMENTS:
            code, size = ELEMENTS[text]
            spelling = text.replace('size_t', 'unsigned long').replace(
                'uint64_t', 'unsigned long')
        else:
            raise Skip('type ' + text)
        if lanes:
            total = lanes * size
            if total not in VECTOR_BYTES:
                raise Skip(f'vector of {total} bytes')
            code = VECTOR_BYTES[total] + code
            spelling = f'__typeof__({spelling} __attribute__((vector_size({total}))))'
            size = total
        if len(pointers) > 1:
            raise Skip('pointer to pointer')
        if pointers:
            self.code = ('^' if constant else '*') + code
            self.spelling = spelling + (' const *' if constant else ' *')
            self.size = 8
        else:
            self.code, self.spelling, self.size = code, spelling, size


class Builtin:
    def __init__(self, row):
        self.name = row['spelling']
        self.file = self.table_name = self.name
        self.extra = []
        match = re.fullmatch(r'(.*?)\((.*)\)', row['prototype_template'])
        if not match:
            raise Skip('prototype ' + row['prototype_template'])
        parameters = [p.strip() for p in re.split(r',(?![^<]*>)', match[2])
                      if p.strip() not in ('', 'void')]
        if any('...' in p for p in parameters):
            raise Skip('variadic')
        self.constants = [i for i, p in enumerate(parameters)
                          if '_Constant' in p]
        self.result = Type(match[1].replace('_Constant ', ''))
        self.parameters = [Type(p.replace('_Constant ', ''))
                           for p in parameters]
        if len(self.constants) > 4:
            raise Skip('more than 4 constant operands')
        self.features = row['features'].replace(' ', '')
        offset = (self.result.size + 15) & ~15
        self.offsets = []
        for i, p in enumerate(self.parameters):
            self.offsets.append(offset)
            if i not in self.constants:
                offset += (p.size + 15) & ~15

    def signature(self):
        return self.result.code + ''.join(p.code for p in self.parameters)

    def flags(self):
        """one choice of the features' alternatives, as -m options"""
        text = self.features
        while '(' in text or '|' in text:
            inner = re.search(r'\(([^()]*)\)', text)
            if inner:
                choice = inner[1].split('|')[0]
                text = text[:inner.start()] + choice + text[inner.end():]
            else:
                text = ','.join(part.split('|')[0] for part in text.split(','))
        return ['-m' + f for f in dict.fromkeys(text.split(',')) if f]

    def source(self, values):
        """one function per tuple of constants; line i+N is function i"""
        lines = []
        types = {}
        for i, t in enumerate([self.result, *self.parameters]):
            if t.size:
                types[i] = f'T{i}'
                lines.append(f'typedef __typeof__({t.spelling}) T{i} '
                             '__attribute__((aligned(1), may_alias));')
        first = len(lines) + 1
        for n, value in enumerate(values):
            arguments = []
            for i, _ in enumerate(self.parameters):
                if i in self.constants:
                    arguments.append(str(value[self.constants.index(i)]))
                else:
                    volatile = ''
                    if self.name in UNFOLDED:
                        volatile = 'volatile '
                    arguments.append(
                        f'*({volatile}T{i + 1} *)(p + {self.offsets[i]})')
            call = f'{self.name}({", ".join(arguments)})'
            if self.result.size:
                call = f'*(T0 *)p = {call}'
            lines.append(f'void s{n}(char *p) {{ {call}; }}')
        return '\n'.join(lines) + '\n', first


def sections(path):
    data = path.read_bytes()
    shoff, = struct.unpack_from('<Q', data, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', data, 0x3a)
    headers = [struct.unpack_from('<IIQQQQ', data, shoff + i * shentsize)
               for i in range(shnum)]
    strings = headers[shstrndx][4]
    found = {}
    for name, _, _, _, offset, size in headers:
        end = data.index(b'\0', strings + name)
        found[data[strings + name:end].decode()] = data[offset:offset + size]
    return found


def with_constants(path, name, code):
    """(constants, code): the constants the code (its ret off) reads
    rip-relative, and the code with those displacements resolved for the
    constants placed, aligned, right before it; None if it refers to anything
    else"""
    data = path.read_bytes()
    shoff, = struct.unpack_from('<Q', data, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', data, 0x3a)
    headers = [struct.unpack_from('<IIQQQQIIQ', data, shoff + i * shentsize)
               for i in range(shnum)]
    strings = headers[shstrndx][4]

    def title(h):
        return data[strings + h[0]:data.index(b'\0', strings + h[0])].decode()

    by_title = {title(h): h for h in headers}
    relocations = by_title[f'.rela.text.{name}']
    symbols = by_title['.symtab']
    pool = bytearray()
    placed = {}
    patches = []
    for at in range(relocations[4], relocations[4] + relocations[5], 24):
        offset, info, addend = struct.unpack_from('<QQq', data, at)
        _, _, _, section, value, _ = struct.unpack_from(
            '<IBBHQQ', data, symbols[4] + 24 * (info >> 32))
        target = headers[section]
        # R_X86_64_PC32 into a constant section
        if info & 0xffffffff != 2 or not title(target).startswith('.rodata'):
            return None
        if section not in placed:
            # sh_addralign: the pool itself is placed at 64
            pool += bytes(-len(pool) % max(target[8], 1))
            placed[section] = len(pool)
            pool += data[target[4]:target[4] + target[5]]
        patches.append((offset, placed[section] + value + addend))
    body = bytearray(code)
    for offset, position in patches:
        struct.pack_into('<i', body, offset, position - len(pool) - offset)
    return bytes(pool), bytes(body)


def compile_values(builtin, values, work):
    """{values: code} of those clang accepts, and the first error"""
    left = list(values)
    first_error = ''
    while left:
        source, first = builtin.source(left)
        c = work / f'{builtin.file}.c'
        o = work / f'{builtin.file}.o'
        c.write_text(source)
        run = subprocess.run(
            [CLANG, '--target=x86_64-linux-gnu', '-march=x86-64', *builtin.flags(),
             *builtin.extra,
             '-O2', '-ffreestanding', '-ffunction-sections', '-mno-red-zone',
             '-fomit-frame-pointer', '-fno-asynchronous-unwind-tables',
             '-fno-stack-protector', '-fcf-protection=none', '-ferror-limit=0',
             '-c', str(c), '-o', str(o)], capture_output=True, text=True)
        if run.returncode == 0:
            break
        bad = {int(line) - first for line in
               re.findall(rf'{re.escape(str(c))}:(\d+):\d+: error', run.stderr)}
        if not first_error:
            errors = re.findall(r'error: (.*)', run.stderr)
            first_error = errors[0] if errors else run.stderr.strip()[:80]
        bad = {n for n in bad if 0 <= n < len(left)}
        if not bad:
            # a backend failure names no line: one value at a time
            if len(left) > 1 and 'Cannot select' in run.stderr:
                codes = {}
                for value in left:
                    one, _ = compile_values(builtin, [value], work)
                    codes.update(one)
                return codes, first_error
            return {}, first_error
        left = [v for n, v in enumerate(left) if n not in bad]
    if not left:
        return {}, first_error
    found = sections(o)
    listing = subprocess.check_output(
        [OBJDUMP, '-d', '--no-show-raw-insn', str(o)], text=True)
    functions = {}
    for block in re.split(r'\n(?=[0-9a-f]+ <)', listing):
        head = re.match(r'[0-9a-f]+ <s(\d+)>:', block)
        if head:
            functions[int(head[1])] = re.findall(
                r'^\s*[0-9a-f]+:\s+(\S+)', block, re.M)
    codes = {}
    for n, value in enumerate(left):
        code = found[f'.text.s{n}']
        operations = functions[n]
        if (sum(op.startswith('ret') for op in operations) != 1
                or not operations[-1].startswith('ret') or code[-1] != 0xc3
                or any(op.startswith('call') for op in operations)):
            first_error = first_error or 'not straight to one ret'
            continue
        stencil = (b'', code[:-1])
        if f'.rela.text.s{n}' in found:
            stencil = with_constants(o, f's{n}', code[:-1])
            if stencil is None:
                first_error = first_error or 'relocation'
                continue
        codes[value] = stencil
    return codes, first_error


def variants(builtin, work):
    """{constants: code}"""
    try:
        return variants_with(builtin, work)
    except Skip:
        if not builtin.features.startswith('avx512'):
            raise
        builtin.extra = ['-mavx512f', '-mavx512vl', '-mavx512bw', '-mavx512dq']
        return variants_with(builtin, work)


def variants_with(builtin, work):
    count = len(builtin.constants)
    if not count:
        codes, error = compile_values(builtin, [()], work)
        if not codes:
            raise Skip(error)
        return codes
    if count == 1:
        values = [(v,) for v in range(256)]
    else:
        # a valid base, then each position's valid values, then the product
        bases = list(itertools.product((4, 1, 0, 8), repeat=count))
        codes, error = compile_values(builtin, bases, work)
        if not codes:
            raise Skip(error)
        base = next(iter(codes))
        choices = []
        for k in range(count):
            probe = [base[:k] + (v,) + base[k + 1:] for v in range(256)]
            codes, _ = compile_values(builtin, probe, work)
            choices.append([key[k] for key in codes])
        total = 1
        for c in choices:
            total *= len(c)
        if total > 4096:
            raise Skip(f'{total} combinations of constants')
        values = list(itertools.product(*choices))
    codes, error = compile_values(builtin, values, work)
    if not codes:
        raise Skip(error)
    return codes


def patch_position(codes):
    """the one byte that is the constant in every variant, or None"""
    if len(codes) < 3 or len(next(iter(codes))) != 1:
        return None
    if any(pool for pool, _ in codes.values()):
        return None
    items = [(key, code) for key, (_, code) in codes.items()]
    (a, x), (b, y) = items[0], items[1]
    if len(x) != len(y):
        return None
    differing = [i for i in range(len(x)) if x[i] != y[i]]
    if len(differing) != 1:
        return None
    at = differing[0]
    for (value,), code in items:
        if code != x[:at] + bytes([value]) + x[at + 1:]:
            return None
    return at


# clang's type-generic vector builtins that <immintrin.h> uses and the front
# ends have no node for: a stencil per operand shape, named BUILTIN/SHAPE/ARGS,
# SHAPE the vector's bytes (0: a scalar), 'i' or 'f' and the element's bytes
GENERIC = (
    # builtin, element kind, operand counts
    ('__builtin_elementwise_fma', 'f', (3,)),
    ('__builtin_elementwise_sqrt', 'f', (1,)),
    ('__builtin_elementwise_min', 'f', (2,)),
    ('__builtin_elementwise_max', 'f', (2,)),
    ('__builtin_elementwise_fshl', 'i', (3,)),
    ('__builtin_elementwise_fshr', 'i', (3,)),
    ('__builtin_elementwise_popcount', 'i', (1,)),
    ('__builtin_elementwise_bitreverse', 'i', (1,)),
    ('__builtin_elementwise_clzg', 'i', (1, 2)),
    ('__builtin_elementwise_ctzg', 'i', (1, 2)),
    ('__builtin_reduce_mul', 'i', (1,)),
)
ELEMENT_BY_SHAPE = {('i', 1): 'unsigned char', ('i', 2): 'unsigned short',
                    ('i', 4): 'unsigned int', ('i', 8): 'unsigned long long int',
                    ('f', 2): '_Float16', ('f', 4): 'float',
                    ('f', 8): 'double'}
AVX512 = 'avx512f,avx512bw,avx512vl'


def generic_features(name, kind, size, width):
    """the feature sets to try, the least first"""
    if kind == 'f':
        if size == 2:
            return ['avx512fp16,avx512vl']
        if width == 64:
            return ['avx512f']
        if name.endswith('_fma'):
            return ['fma']
        if width == 32:
            return ['avx']
        return ['sse2']
    least = {0: ['sse2'], 16: ['sse2'], 32: ['avx2'], 64: []}[width]
    return least + [AVX512, AVX512 + ',avx512cd,avx512bitalg,avx512vpopcntdq',
                    AVX512 + ',avx512vbmi2,gfni']


def generic_rows():
    for name, kind, counts in GENERIC:
        for (element_kind, size), element in ELEMENT_BY_SHAPE.items():
            if element_kind != kind:
                continue
            for width in (0, 16, 32, 64):
                if width == 0 and name.startswith('__builtin_reduce'):
                    continue
                for count in counts:
                    # (a scalar clzg or ctzg has an int fallback)
                    if width == 0 and count == 2 and name.endswith('zg'):
                        continue
                    operand = element
                    if width:
                        operand = f'_Vector<{width // size}, {element}>'
                    result = operand
                    if name.startswith('__builtin_reduce'):
                        result = element
                    yield (name, f'{name}/{width}{kind}{size}/{count}',
                           f'{result}({", ".join([operand] * count)})',
                           generic_features(name, kind, size, width))


def generic(item, work):
    call, spelled, prototype, features = item
    reason = ''
    for choice in features:
        builtin = Builtin({'spelling': call, 'prototype_template': prototype,
                           'features': choice})
        # a name of its own for the files and the table
        builtin.file = re.sub(r'\W', '_', spelled)
        try:
            codes = variants(builtin, work)
        except Skip as why:
            reason = str(why)
            continue
        builtin.table_name = spelled
        return builtin, codes, None
    return spelled, None, reason


def wanted():
    reader = SRC.parent / 'build/linux/src/clang-builtin-reader'
    resource = subprocess.check_output(
        [CLANG, '-print-resource-dir'], text=True).strip()
    used = set()
    for header in glob.glob(resource + '/include/*intrin*.h'):
        used |= set(re.findall(r'__builtin_ia32_\w+', Path(header).read_text()))
    wired = set(re.findall(
        r'"(__builtin_ia32_\w+)"',
        (SRC / 'frontend/c/builtins-registry.cpp').read_text()))
    wired |= set(re.findall(r'X86_INSTRUCTION\("(\w+)"',
                            registrations.generate_x86(reader)))
    wired |= set(re.findall(r'"(__builtin_\w+)"',
                            registrations.generate_targets(reader)))
    rows = {}
    for filename in ('BuiltinsX86.td', 'BuiltinsX86_64.td'):
        for row in registrations.read_table(reader, filename):
            rows.setdefault(row['spelling'], row)
    return [rows[n] for n in sorted(used & set(rows) - wired)]


def main():
    rows = wanted()
    made, skipped = [], []
    with tempfile.TemporaryDirectory() as directory:
        work = Path(directory)

        def one(row):
            try:
                builtin = Builtin(row)
                return builtin, variants(builtin, work), None
            except Skip as reason:
                return row['spelling'], None, str(reason)

        with concurrent.futures.ThreadPoolExecutor(8) as pool:
            def one_generic(item):
                return generic(item, work)

            for builtin, codes, reason in [*pool.map(one, rows),
                                           *pool.map(one_generic,
                                                     generic_rows())]:
                if codes is None:
                    skipped.append((builtin, reason))
                else:
                    made.append((builtin, codes))

    blob = bytearray()
    offsets = {}

    def place(code):
        if code not in offsets:
            offsets[code] = len(blob)
            blob.extend(code)
        return offsets[code]

    names = [GENERATED, '/* X86_STENCIL (spelling, signature) */']
    table = [GENERATED,
             '/* X86_STENCIL_ROW (features, constant operands as a mask, first',
             '   variant, variants, patched byte or -1), in the names\' order;',
             '   X86_STENCIL_VARIANTS: {constants, one per byte; how many consecutive',
             '   values; offset; code length; bytes of constants before the code}; X86_STENCIL_BYTES: the code. */',
             '#ifdef X86_STENCIL_ROW']
    variant_lines = []
    for builtin, codes in made:
        names.append(f'X86_STENCIL("{builtin.table_name}", "{builtin.signature()}")')
        mask = sum(1 << i for i in builtin.constants)
        at = patch_position(codes)
        first = len(variant_lines)
        items = sorted(codes.items())
        if at is not None:
            # one stencil; the values it takes are listed with it
            shared = items[0][1]
            items = [(value, shared) for value, _ in items]
        # consecutive constants with the same code share a row
        ranges = []
        for value, code in items:
            key = sum((v & 0xff) << (8 * k) for k, v in enumerate(value))
            pool, body = code
            ranges.append((key, place(pool + body), len(body), len(pool)))
        ranges.sort()
        merged = []
        for key, offset, length, pool in ranges:
            if (merged and merged[-1][0] + merged[-1][1] == key
                    and merged[-1][2:] == [offset, length, pool]):
                merged[-1][1] += 1
            else:
                merged.append([key, 1, offset, length, pool])
        for key, keys, offset, length, pool in merged:
            variant_lines.append(
                f'{{{key}u,{keys},{offset},{length},{pool}}},')
        patched = -1
        if at is not None:
            patched = at
        table.append(f'X86_STENCIL_ROW("{builtin.features}", {mask}, {first}, '
                     f'{len(variant_lines) - first}, {patched})')
    table += ['#endif', '#ifdef X86_STENCIL_VARIANTS', *variant_lines, '#endif',
              '#ifdef X86_STENCIL_BYTES']
    for i in range(0, len(blob), 16):
        table.append(''.join(f'{b},' for b in blob[i:i + 16]))
    table.append('#endif')
    for name, reason in skipped:
        names.append(f'/* {name}: {reason} */')
    NAMES.write_text('\n'.join(names) + '\n')
    CODE.write_text('\n'.join(table) + '\n')
    print(f'{len(made)} stencils, {len(variant_lines)} variants, '
          f'{len(blob)} bytes of code, {len(skipped)} skipped')


if __name__ == '__main__':
    main()
