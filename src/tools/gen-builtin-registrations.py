#!/usr/bin/env python3
"""Generate vroom builtin registrations from the pinned Clang records."""

import argparse
from dataclasses import dataclass
import json
from pathlib import Path
import re
import subprocess

SRC = Path(__file__).resolve().parents[1]
INCLUDE = SRC.parent / 'contrib/clang-builtins/clang/include'
GENERATED = '/* Generated by src/tools/gen-builtin-registrations.py. */'

# Vroom's ABI-relative signature codes. Explicit-width typedefs use the
# fixed-width integer representations already used by the AST builtins.
TYPES = {
    'int': 'i',
    'long int': 'l',
    'long long int': 'w',
    'unsigned char': 'C',
    'unsigned short': 'h',
    'unsigned int': 'u',
    'unsigned long int': 'L',
    'unsigned long long int': 'W',
    'unsigned long long int *': 'R',
    'uint32_t': 'u',
    'uint64_t': 'W',
}


@dataclass(frozen=True)
class Family:
    record: str
    spelling: str
    id_prefix: str
    fold: str
    suffixes: tuple[str, ...]
    flags: int = 1


LONG = ('', 'l', 'll')
WORDS = ('16', '32', '64')
BYTES = ('8', *WORDS)
FAMILIES = (
    Family('Clz', 'clz', 'CLZ', 'clz', LONG),
    Family('Ctz', 'ctz', 'CTZ', 'ctz', LONG),
    Family('Popcount', 'popcount', 'POPCOUNT', 'popcount', LONG),
    Family('Parity', 'parity', 'PARITY', 'parity', LONG),
    Family('Clrsb', 'clrsb', 'CLRSB', 'clrsb', LONG),
    Family('BSwap', 'bswap', 'BSWAP', 'bswap', WORDS),
    Family('Bitreverse', 'bitreverse', 'BITREVERSE', 'bitreverse', BYTES),
    Family('RotateLeft', 'rotateleft', 'ROTL', 'rotate_left', BYTES, 0),
    Family('RotateRight', 'rotateright', 'ROTR', 'rotate_right', BYTES, 0),
)


def signature(row):
    match = re.fullmatch(r'([^()]+)\(([^()]*)\)', row['prototype_template'])
    if not match:
        raise ValueError(f"{row['spelling']}: unsupported prototype {row['prototype_template']!r}")
    result, parameters = match.groups()
    codes = []
    for ty in (result, *parameters.split(',')):
        ty = re.sub(r'\bT\b', lambda _: row['type_substitution'], ty)
        ty = ' '.join(ty.split())
        if ty not in TYPES:
            raise ValueError(f"{row['spelling']}: unsupported integer type {ty!r}")
        codes.append(TYPES[ty])
    return ''.join(codes)


def read_table(reader, filename):
    entry = INCLUDE / 'clang/Basic' / filename
    data = subprocess.check_output(
        [str(reader.resolve()), '--metadata', str(INCLUDE), str(entry)], text=True)
    return [json.loads(line) for line in data.splitlines()]


def generate_integer(reader):
    by_record = {}
    for row in read_table(reader, 'Builtins.td'):
        by_record.setdefault(row['record'], []).append(row)
    lines = [
        GENERATED,
        '/* Columns are spelling, AST id, C flags, ABI-relative signature and fold. */',
    ]
    names = set()
    for family in FAMILIES:
        prefix = f'__builtin_{family.spelling}'
        expected = {prefix + suffix for suffix in family.suffixes}
        rows = [row for row in by_record.get(family.record, [])
                if row['spelling'] in expected]
        actual = {row['spelling'] for row in rows}
        if expected != actual or len(rows) != len(actual) or names & actual:
            raise ValueError(f'{family.record}: expected {sorted(expected)}, got {sorted(actual)}')
        names.update(actual)
        variants = {row['spelling']: row for row in rows}
        for suffix in family.suffixes:
            name = prefix + suffix
            row = variants[name]
            if (row['alias_of'] or row['features'] or row['header'] or row['languages'] or
                    set(row['attributes']) != {'Const', 'Constexpr', 'NoThrow'}):
                raise ValueError(f'{name}: unexpected availability or attributes')
            id_ = f'CC_BUILTIN_{family.id_prefix}{suffix.upper()}'
            lines.append(f'INTEGER_BUILTIN("{name}", {id_}, {family.flags}, '
                         f'"{signature(row)}", {family.fold})')
    return '\n'.join(lines) + '\n'


# C23's <stdbit.h> functions in clang's custom-type-checked spellings
# (CustomTypeChecking, prototype "void(...)" or "bool(...)": the operand type
# decides).  The operation names are the C++ front end's builtin_stdc_op.
# The C front end lowers the rotations as nodes and two counts as library
# bodies; the others are known to analysis and constant evaluation only
# (the C++ front end refuses a call outside a constant expression with the
# reason).  Columns of the lowering: (kind, AST id, C flags, C signature).
STDC_RECORDS = (
    ('StdcLeadingZeros', 'leading_zeros', None),
    ('StdcLeadingOnes', 'leading_ones', None),
    ('StdcTrailingZeros', 'trailing_zeros', ('body', '', 1, 'u.')),
    ('StdcTrailingOnes', 'trailing_ones', None),
    ('StdcFirstLeadingZero', 'first_leading_zero', None),
    ('StdcFirstLeadingOne', 'first_leading_one', None),
    ('StdcFirstTrailingZero', 'first_trailing_zero', None),
    ('StdcFirstTrailingOne', 'first_trailing_one', None),
    ('StdcCountZeros', 'count_zeros', None),
    ('StdcCountOnes', 'count_ones', ('body', '', 1, 'u.')),
    ('StdcHasSingleBit', 'has_single_bit', None),
    ('StdcBitWidth', 'bit_width', None),
    ('StdcBitFloor', 'bit_floor', None),
    ('StdcBitCeil', 'bit_ceil', None),
    ('StdcRotateLeft', 'rotate_left', ('node', 'CC_BUILTIN_STDC_ROTL', 0, 'u..')),
    ('StdcRotateRight', 'rotate_right', ('node', 'CC_BUILTIN_STDC_ROTR', 0, 'u..')),
    ('Bitreverseg', 'bitreverse', None),
)


def generate_stdc(reader):
    by_record = {}
    for row in read_table(reader, 'Builtins.td'):
        by_record.setdefault(row['record'], []).append(row)
    lines = [
        GENERATED,
        '/* STDC_NODE (spelling, operation, AST id, C flags, C signature): the C',
        '   front end has a node; STDC_BODY (spelling, operation, C flags, C',
        '   signature): a library body there; STDC_OP (spelling, operation):',
        '   neither.  The operation is builtin_stdc_op\'s name. */',
    ]
    for record, op, lowering in STDC_RECORDS:
        rows = by_record.get(record, [])
        if len(rows) != 1:
            raise ValueError(f'{record}: expected one record, got {len(rows)}')
        row, = rows
        name = row['spelling']
        expected = '__builtin_bitreverseg' if op == 'bitreverse' else f'__builtin_stdc_{op}'
        if name != expected:
            raise ValueError(f'{record}: expected spelling {expected}, got {name}')
        if (row['alias_of'] or row['features'] or row['header'] or row['languages'] or
                set(row['attributes']) != {'NoThrow', 'Const', 'Constexpr', 'CustomTypeChecking'} or
                not row['prototype_template'].endswith('(...)')):
            raise ValueError(f'{name}: unexpected availability, attributes or prototype')
        if lowering is None:
            lines.append(f'STDC_OP("{name}", {op})')
        elif lowering[0] == 'node':
            lines.append(f'STDC_NODE("{name}", {op}, {lowering[1]}, {lowering[2]}, "{lowering[3]}")')
        else:
            lines.append(f'STDC_BODY("{name}", {op}, {lowering[2]}, "{lowering[3]}")')
    return '\n'.join(lines) + '\n'


# clang's alignment builtins (custom type checking, prototype "T(void const*,
# size_t)": the operand type decides).  Only the C++ front end has them
# (analysis, constant evaluation); the operation number is its `align` form's
# `which`.
ALIGN_RECORDS = (
    ('AlignUp', '__builtin_align_up', 0),
    ('AlignDown', '__builtin_align_down', 1),
    ('IsAligned', '__builtin_is_aligned', 2),
)


def generate_align(reader):
    by_record = {}
    for row in read_table(reader, 'Builtins.td'):
        by_record.setdefault(row['record'], []).append(row)
    lines = [
        GENERATED,
        '/* ALIGN_OP (spelling, operation): 0 up, 1 down, 2 is_aligned. */',
    ]
    for record, name, op in ALIGN_RECORDS:
        rows = by_record.get(record, [])
        if len(rows) != 1:
            raise ValueError(f'{record}: expected one record, got {len(rows)}')
        row, = rows
        if row['spelling'] != name:
            raise ValueError(f'{record}: expected spelling {name}, got {row["spelling"]}')
        if (row['alias_of'] or row['features'] or row['header'] or row['languages'] or
                set(row['attributes']) != {'NoThrow', 'Const', 'Constexpr', 'CustomTypeChecking'}):
            raise ValueError(f'{name}: unexpected availability or attributes')
        lines.append(f'ALIGN_OP("{name}", {op})')
    return '\n'.join(lines) + '\n'


def generate_targets(reader):
    # The compiler owns the dispatch IDs. The input owns the spellings,
    # prototypes and prerequisites. Only these wired operations are emitted.
    groups = (
        ('BuiltinsX86.td', '__builtin_ia32_', 'crc32', (
            ('crc32qi', 'X86_CRC32'), ('crc32hi', 'X86_CRC32'),
            ('crc32si', 'X86_CRC32'),
        )),
        ('BuiltinsX86_64.td', '__builtin_ia32_', 'crc32', (
            ('crc32di', 'X86_CRC32'),
        )),
        ('BuiltinsX86_64.td', '__builtin_ia32_', '', (
            ('addcarryx_u64', 'X86_ADDCARRY'),
        )),
        ('BuiltinsAArch64.td', '__builtin_arm_', '', (
            ('rbit', 'BITREVERSE32'), ('rbit64', 'BITREVERSE64'),
            ('clz', 'CLZ'), ('clz64', 'CLZLL'),
            ('cls', 'CLRSB'), ('cls64', 'CLRSBLL'),
        )),
    )
    tables = {filename: read_table(reader, filename)
              for filename in dict.fromkeys(group[0] for group in groups)}
    lines = [GENERATED]
    for filename, prefix, features, entries in groups:
        for suffix, id_ in entries:
            name = prefix + suffix
            variants = [r for r in tables[filename] if r['spelling'] == name]
            if len(variants) != 1:
                raise ValueError(f'{filename}: expected one record for {name}')
            row, = variants
            required = {'NoThrow'}
            if id_ != 'X86_ADDCARRY':
                required.add('Const')
            if prefix == '__builtin_ia32_':
                required.add('Constexpr')
            if (row['alias_of'] or row['header'] or row['languages'] or
                    row['features'] != features or set(row['attributes']) != required):
                raise ValueError(f'{filename}: unexpected availability or attributes for {name}')
            flags = int('Const' in required)
            lines.append(f'    {{"{name}", CC_BUILTIN_{id_}, {flags}, "{signature(row)}"}},')
    fp16 = read_table(reader, 'arm_fp16.td')
    for operation, id_ in (('vaddh_f16', 'ARM_FP16_ADD'), ('vsubh_f16', 'ARM_FP16_SUB')):
        name = '__builtin_neon_' + operation
        variants = [row for row in fp16 if row['spelling'] == name]
        if len(variants) != 1:
            raise ValueError(f'arm_fp16.td: expected one record for {name}')
        row, = variants
        if (row['prototype_format'] != 'neon' or row['type_substitution'] != 'Sh' or
                row['operand_variant'] != 'Sh' or row['features'] != 'fullfp16' or
                row['prototype_template'] != '111'):
            raise ValueError(f'arm_fp16.td: unexpected scalar FP16 form for {name}')
        # "1" is a scalar operand of the record's base type (half).
        prototype = row['prototype_template'].replace('1', 'e')
        lines.append(f'    {{"{name}", CC_BUILTIN_{id_}, 0, "{prototype}"}},')
    return '\n'.join(lines) + '\n'


def generate_stubs(reader):
    groups = {
        'Builtins.td': 3,
        'BuiltinsX86.td': 2,
        'BuiltinsX86_64.td': 2,
        'BuiltinsAArch64.td': 1,
        'arm_neon.td': 1,
        'arm_fp16.td': 1,
        'arm_sve.td': 1,
        'arm_sme.td': 1,
    }
    names = {}
    for filename, mask in groups.items():
        entry = INCLUDE / 'clang/Basic' / filename
        result = subprocess.check_output(
            [str(reader.resolve()), str(INCLUDE), str(entry)], text=True)
        for spelling in result.splitlines():
            if spelling.startswith('__builtin_'):
                if not re.fullmatch(r'__builtin_[A-Za-z_0-9]+', spelling):
                    raise ValueError(f'{filename}: invalid stub spelling {spelling!r}')
                suffix = spelling[len('__builtin_'):]
                names[suffix] = names.get(suffix, 0) | mask

    # Use offsets rather than pointers to keep this table free of relocations.
    # Store the suffix only, since lookup has already checked the common prefix.
    lines = [GENERATED, '', 'static const char cc_builtin_stub_names[] =']
    offset, offsets = 0, []
    for name, mask in sorted(names.items()):
        lines.append(f'    "{name}\\0"')
        offsets.append(str((offset << 2) | mask))
        offset += len(name) + 1
    lines[-1] += ';'
    lines.extend(['', 'static const uint32_t cc_builtin_stub_offsets[] = {'])
    for start in range(0, len(offsets), 10):
        lines.append('    ' + ', '.join(offsets[start:start + 10]) + ',')
    return '\n'.join([*lines, '};', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reader', type=Path, required=True, help='built clang-builtin-reader')
    parser.add_argument('--output-root', type=Path, default=SRC / 'include',
                        help='generated include root (default: src/include)')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        outputs = {
            args.output_root / 'frontend/integer-builtins.inc': generate_integer(args.reader),
            args.output_root / 'frontend/stdc-builtins.inc': generate_stdc(args.reader),
            args.output_root / 'frontend/align-builtins.inc': generate_align(args.reader),
            args.output_root / 'frontend/c/target-builtins.inc': generate_targets(args.reader),
            args.output_root / 'frontend/c/builtin-stubs.inc': generate_stubs(args.reader),
        }
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        parser.exit(1, f'{error}\n')
    for output, generated in outputs.items():
        if args.check:
            if not output.exists() or output.read_text() != generated:
                parser.exit(1, f'{output.name} is stale. Run make -C src builtin-registrations\n')
        else:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(generated)


if __name__ == '__main__':
    main()
