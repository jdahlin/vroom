#!/usr/bin/env python3
"""gen-cxx-builtins.py: src/frontend/cxx/codegen/builtins.list -> builtins.inc

    src/tools/gen-cxx-builtins.py [--check] [--coverage LIBCXX_INCLUDE_DIR]

The C++ front end's builtins, one table sorted by name (codegen/builtin.c looks a name up by
binary search, then picks the entry with the call's number of arguments).  The list is checked
against the C front end's tables:
  - a `node`, `fclass` or `atomic` entry must name one of frontend/c/builtin-table.c's builtins;
  - a `lib` entry must not be one of clang's library builtins (frontend/c/libbuiltins.inc,
    gen-libbuiltins.py), which the C++ front end takes from there;
  - every signature letter must be one cc_builtin_signature_type reads (or `.`, `*`, `&`, `=`).
--check: fail if builtins.inc is not what the list gives (the build compiles builtins.inc).
--coverage DIR: the compiler builtins libc++'s headers in DIR call (__builtin_*, __c11_atomic_*, and the
__atomic_* that are C's builtins) that are neither in the list nor clang's library builtins: what the
C++ front end does not have yet.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'frontend')
LIST = os.path.join(SRC, 'cxx', 'codegen', 'builtins.list')
OUT = os.path.join(SRC, 'cxx', 'codegen', 'builtins.inc')
KINDS = {'lib': 'CXX_BI_LIB', 'node': 'CXX_BI_NODE', 'fclass': 'CXX_BI_FCLASS', 'atomic': 'CXX_BI_ATOMIC', 'special': 'CXX_BI_SPECIAL', 'parsed': None}
LETTERS = set('vbChiulLwWzdfcDpPsS')	# frontend/c/builtin-table.c cc_builtin_signature_type
EXTRA = set('.*&=')


def fail(msg):
    sys.exit(f'gen-cxx-builtins.py: {msg}')


ctable = set(re.findall(r'\{ "(__[A-Za-z0-9_]+)", BI_', open(os.path.join(SRC, 'c', 'builtin-table.c')).read()))
libtable = set(re.findall(r'\{ "(__builtin_[A-Za-z0-9_]+)", "', open(os.path.join(SRC, 'c', 'libbuiltins.inc')).read()))
entries, seen, listed = [], set(), set()
for n, line in enumerate(open(LIST), 1):
    line = line.split('#', 1)[0].split()
    if not line:
        continue
    if len(line) < 3:
        fail(f'{LIST}:{n}: expected name, kind, signature')
    name, kind, sig, *rest = line
    if kind not in KINDS:
        fail(f'{LIST}:{n}: {name}: unknown kind {kind}')
    if not sig or any(ch not in LETTERS | EXTRA for ch in sig) or (sig[0] in '.' or any(ch in '*&=' for ch in sig[1:])):
        fail(f'{LIST}:{n}: {name}: bad signature {sig!r}')
    if (kind == 'lib') != bool(rest) or len(rest) > 1:
        fail(f'{LIST}:{n}: {name}: a lib entry (and only one) has a symbol')
    if kind in ('node', 'fclass', 'atomic') and name not in ctable:
        fail(f'{LIST}:{n}: {name}: not in frontend/c/builtin-table.c')
    if kind == 'lib' and name in libtable:
        fail(f'{LIST}:{n}: {name}: one of clang\'s library builtins (libbuiltins.inc): not listed here')
    if (name, len(sig) - 1) in seen:
        fail(f'{LIST}:{n}: {name}: a second entry with {len(sig) - 1} parameters')
    seen.add((name, len(sig) - 1))
    listed.add(name)
    if KINDS[kind]:
        entries.append((name, len(sig) - 1, KINDS[kind], sig, rest[0] if rest else None))
entries.sort()
text = ['/* generated by src/tools/gen-cxx-builtins.py from builtins.list: do not edit */']
for name, _, kind, sig, sym in entries:
    text.append(f'\t{{ "{name}", {kind}, "{sig}", {f"{chr(34)}{sym}{chr(34)}" if sym else "NULL"} }},')
text = '\n'.join(text) + '\n'
if '--coverage' in sys.argv[1:]:
    top = sys.argv[sys.argv.index('--coverage') + 1]
    catoms = {n for n in ctable if n.startswith('__atomic_')}
    use = {}
    for root, _, files in os.walk(top):
        for f in files:
            path = os.path.join(root, f)
            try:
                text_ = open(path, errors='replace').read()
            except OSError:
                continue
            for m in re.finditer(r'\b(__builtin_[A-Za-z0-9_]+|__c11_atomic_[a-z_]+|__atomic_[a-z_]+)\s*\(', text_):
                n_ = m.group(1)
                if n_.startswith('__atomic_') and n_ not in catoms:
                    continue	# (libc++'s own __atomic_* functions)
                use.setdefault(n_, set()).add(os.path.relpath(path, top))
    missing = sorted(n_ for n_ in use if n_ not in listed and n_ not in libtable)
    print(f'gen-cxx-builtins: libc++ calls {len(use)} builtins; {len(use) - len(missing)} listed or clang\'s library builtins, '
          f'{len(missing)} not:')
    for n_ in missing:
        print(f'  {n_:40} {", ".join(sorted(use[n_])[:3])}')
    sys.exit(0)
if '--check' in sys.argv[1:]:
    if not os.path.exists(OUT) or open(OUT).read() != text:
        fail('builtins.inc is not up to date: run src/tools/gen-cxx-builtins.py')
    print(f'gen-cxx-builtins: {len(entries)} builtins, builtins.inc up to date')
else:
    open(OUT, 'w').write(text)
    print(f'gen-cxx-builtins: {len(entries)} builtins -> {os.path.relpath(OUT)}')
