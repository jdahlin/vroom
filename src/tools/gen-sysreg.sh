#!/bin/sh
# Generate a64sysreg.inc: the named AArch64 system registers, taken once
# from LLVM's disassembler (every MRS/MSR encoding with op0 = 2 or 3).
# Output: { "name", encoding16, rw } sorted by lowercase name; rw bit 0 =
# readable (mrs), bit 1 = writable (msr).
LLVM=${LLVM:-/opt/homebrew/opt/llvm}
python3 - "$LLVM/bin/llvm-mc" > "$(dirname "$0")/../arch/a64/a64sysreg.inc" <<'PY'
import subprocess, sys, re
mc = sys.argv[1]
lines = []
for base in (0xd5300000, 0xd5100000):
    for e in range(0x8000):
        w = base | e << 5
        lines.append(' '.join('0x%02x' % ((w >> 8*i) & 255) for i in range(4)))
out = subprocess.run([mc, '-triple', 'aarch64', '-mattr=+all', '-disassemble'],
                     input='\n'.join(lines), capture_output=True, text=True).stdout
regs = {}
for l in out.splitlines():
    m = re.match(r'\s+(mrs|msr)\s+(?:x0, )?(\w+)(?:, x0)?$', l)
    if not m or re.match(r'S[0-9]_', m.group(2)): continue
    name = m.group(2).lower()
    regs.setdefault(name, [None, 0])
    regs[name][1] |= 1 if m.group(1) == 'mrs' else 2
# re-assemble each name to get its encoding (mrs, else msr)
names = sorted(regs)
src = '\n'.join(('mrs x0, %s' if regs[n][1] & 1 else 'msr %s, x0') % n for n in names)
enc = subprocess.run([mc, '-triple', 'aarch64', '-mattr=+all', '-show-encoding'],
                     input=src, capture_output=True, text=True).stdout
encs = re.findall(r'encoding: \[0x(..),0x(..),0x(..),0x(..)\]', enc)
assert len(encs) == len(names), (len(encs), len(names))
print('/* generated by gen-sysreg.sh from llvm-mc; do not edit */')
for n, e in zip(names, encs):
    w = int(e[3] + e[2] + e[1] + e[0], 16)
    print('{ "%s", 0x%04x, %d },' % (n, (w >> 5) & 0xffff | 0x8000, regs[n][1]))
PY
