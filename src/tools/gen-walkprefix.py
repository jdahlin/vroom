#!/usr/bin/env python3
"""
src/codegen/walk/prefix.h: the walker's function names, for compiling codegen/walk/*.c
a second time under other names (PLAN-vir.md V2, SPEC-vir.md X1).

The walker is one source for every CPU: its own functions are walk_*, the target
is reached through WALK_LOWER(name).  A second instantiation (the VIR builder: WALK_LOWER
-> vir_, the walker's own names -> vir_wk_...) is one more translation unit
that defines WALK_PREFIX and WALK_LOWER_PREFIX and includes the walker files.  When
WALK_PREFIX is defined, prefix.h renames every function the walker defines;
when it is not, the header is empty and nothing changes.

The list is taken from the walker's own function definitions (a function at
file scope in walk/*.c, VPRIV or static, named walk_*), so it cannot go stale
silently: --check fails if the checked-in header differs, if a walk_* function
declared in walk.h is not defined in walk/*.c (it would be renamed but not
found), or if walk/*.c calls a name that WALK_LOWER() should have made (x64_*).

  src/tools/gen-walkprefix.py           regenerate src/codegen/walk/prefix.h
  src/tools/gen-walkprefix.py --check   exit 1 if it is out of date or inconsistent
"""
import glob, os, re, sys

R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))	# src/tools/ -> the checkout
D = f'{R}/src/codegen/walk'
OUT = f'{D}/prefix.h'
UNOUT = f'{D}/unprefix.h'

DEF = re.compile(r'^(?:VPRIV|static)\b(?:__attribute__\(\(.*?\)\)|[^();=])*?\b(walk_\w+)\s*\(', re.M)


def defined():
    names = {}
    for f in sorted(glob.glob(f'{D}/*.c')):
        src = open(f).read()
        for m in DEF.finditer(src):
            # a definition has its body after the closing parenthesis; a
            # prototype ends in ';' (skip those)
            i, depth = m.end(), 1
            while depth:
                depth += (src[i] == '(') - (src[i] == ')')
                i += 1
            if src[i:].lstrip().startswith('{'):
                names.setdefault(m.group(1), os.path.basename(f))
    return names


def generate(names):
    out = ['/* Generated by src/tools/gen-walkprefix.py from the function definitions in the walker sources; do not edit.',
           ' * Included by walk.h and proto.h.  With WALK_PREFIX defined (a second instantiation of the walker,',
           ' * which also defines WALK_LOWER_PREFIX) every function the walker defines gets that prefix; without it',
           ' * this header is empty.  No include guard: the second instantiation includes it again, and',
           ' * unprefix.h undoes it. */',
           '#ifdef WALK_PREFIX',
           '#define WALK_PASTE_(p, n) p##n',
           '#define WALK_PASTE(p, n) WALK_PASTE_(p, n)',	# (the extra level expands WALK_PREFIX first)
           '#define WALK_NAME(n) WALK_PASTE(WALK_PREFIX, n)']
    for n in sorted(names):
        out.append(f'#define {n} WALK_NAME({n})')
    out += ['#endif', '']
    return '\n'.join(out)


def ungenerate(names):
    out = ['/* Generated by src/tools/gen-walkprefix.py; do not edit.  Ends a second instantiation of the walker',
           ' * (prefix.h with WALK_PREFIX): the walker\'s names, WALK_LOWER and the prefixes are what they were before',
           ' * it, so that later files of the same translation unit see the first instantiation. */',
           '#undef WALK_PREFIX', '#undef WALK_LOWER_PREFIX', '#undef WALK_LOWER', '#define WALK_LOWER(name) x64_##name']
    for n in sorted(names):
        out.append(f'#undef {n}')
    out.append('')
    return '\n'.join(out)


def main():
    names = defined()
    bad = []
    hdr = open(f'{D}/walk.h').read() + open(f'{D}/proto.h').read()
    for n in sorted(set(re.findall(r'\b(walk_\w+)\s*\(', hdr))):
        if n not in names:
            bad.append(f'{n}: declared in walk.h/proto.h, not defined in walk/*.c')
    for f in sorted(glob.glob(f'{D}/*.c')):
        for i, line in enumerate(open(f), 1):
            if re.search(r'\bx64_\w+', line) and 'WALK_LOWER(' not in line:
                bad.append(f'{os.path.basename(f)}:{i}: a target name outside WALK_LOWER(): {line.strip()}')
    text, untext = generate(names), ungenerate(names)
    if '--check' in sys.argv:
        for path, want in ((OUT, text), (UNOUT, untext)):
            cur = open(path).read() if os.path.exists(path) else ''
            if cur != want:
                bad.append(f'{path} is out of date: run src/tools/gen-walkprefix.py')
        for b in bad:
            print(b, file=sys.stderr)
        print(f'walkprefix: {len(names)} names' + ('' if not bad else f', {len(bad)} problems'))
        sys.exit(1 if bad else 0)
    for b in bad:
        print('warning:', b, file=sys.stderr)
    open(OUT, 'w').write(text)
    open(UNOUT, 'w').write(untext)
    print(f'{OUT}, {UNOUT}: {len(names)} names')


main()
