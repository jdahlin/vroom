#!/usr/bin/env python3
"""Generate src/frontend/pp/ppdata-cxx.inc: clang++'s predefined macros as a
difference from clang's C ones, per target and C++ standard (PLAN-cxx.md X2).

  src/tools/gen-cxxpredef.py [CLANG]     (default clang-23)

driver/predef.c appends the C base table (ppdata-predef.inc, ppdata-x86.inc)
and then, for a C++ job, the entry for its target and -std: #undef lines for
macros C has and C++ does not, #define lines for the new or changed ones.
The C side is clang's default C standard (gnu17), so __STDC_VERSION__ is
201710L there; the C++ delta removes it.  -fno-exceptions and -fno-rtti
only remove macros (the script checks); what they remove is per entry.
It also writes ppdata-cxx-has.inc: clang++'s nonzero answers to the
__has_builtin/feature/extension/attribute/cpp_attribute queries that libc++,
nlohmann/json and doctest can ask (their literal queries, and every
identifier in them, since libc++ wraps queries in macros), per target and
standard.  The preprocessor looks there first in C++; a name not in it has
the answer 0 for __has_cpp_attribute, __has_feature and __has_extension, and
falls through to the C table for the others.
Run once per clang release; the output is checked in.
CXX_CORPUS: directories to collect queries from (default: libc++'s headers
and work/cxx's json and doctest).
"""
import glob, os, re, subprocess, sys, tempfile

CLANG = sys.argv[1] if len(sys.argv) > 1 else "clang-23"
CLANGXX = CLANG.replace("clang", "clang++", 1)
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "frontend", "pp", "ppdata-cxx.inc")
TARGETS = [("PP_LINUX_X86_64", "x86_64-linux-gnu"), ("PP_LINUX_AARCH64", "aarch64-linux-gnu"),
           ("PP_DARWIN", "arm64-apple-darwin")]
STDS = [98, 11, 14, 17, 20, 23, 26]


def dm(cc, args):
    out = subprocess.run([cc, *args, "-dM", "-E", "-"], input="", capture_output=True, text=True, check=True).stdout
    d = {}
    for l in out.splitlines():
        if l.startswith("#define "):
            k, _, v = l[8:].partition(" ")
            d[k] = v
    return d


def delta(c, x):
    lines = [f"#undef {k}" for k in sorted(c) if k not in x]
    for k in sorted(x):
        if c.get(k) != x[k]:
            if k in c:
                lines.append(f"#undef {k}")
            lines.append(f"#define {k} {x[k]}".rstrip())
    return "".join(l + "\\n" for l in lines)


def cstr(s):
    return '"' + s.replace("\\\\", "\\\\").replace('"', '\\"') + '"'


def main():
    rows = []
    for tgt, triple in TARGETS:
        c = dm(CLANG, ["-target", triple, "-x", "c"])
        for std in STDS:
            for gnu in (0, 1):
                name = ("gnu++" if gnu else "c++") + ("98" if std == 98 else str(std))
                x = dm(CLANGXX, ["-target", triple, "-x", "c++", "-std=" + name])
                xa = ["-target", triple, "-x", "c++", "-std=" + name]
                ne, nr = dm(CLANGXX, xa + ["-fno-exceptions"]), dm(CLANGXX, xa + ["-fno-rtti"])
                if set(ne) - set(x) or set(nr) - set(x) or any(ne[k] != x[k] for k in ne) or any(nr[k] != x[k] for k in nr):
                    sys.exit(f"{triple} {name}: -fno-exceptions/-fno-rtti add or change macros")
                rows.append((tgt, std, gnu, delta(c, x), delta(x, ne), delta(x, nr)))
    with open(OUT, "w") as f:
        f.write("/* generated by src/tools/gen-cxxpredef.py from " +
                subprocess.run([CLANG, "--version"], capture_output=True, text=True).stdout.splitlines()[0] +
                "; do not edit */\n")
        f.write("static const struct { int target, standard, gnu; const char *delta, *no_exceptions, *no_rtti; } predef_cxx[] = {\n")
        for tgt, std, gnu, d, ne, nr in rows:
            f.write(f"\t{{ {tgt}, {std}, {gnu}, \"{d}\", \"{ne}\", \"{nr}\" }},\n")
        f.write("};\n")
    print(f"wrote {OUT}: {len(rows)} entries")
    has_table()


QUERIES = ["__has_builtin", "__has_attribute", "__has_feature", "__has_extension", "__has_cpp_attribute",
           "__has_constexpr_builtin"]


def has_table():
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
    llvm = os.path.dirname(os.path.dirname(os.path.realpath(subprocess.run(["which", CLANG], capture_output=True, text=True).stdout.strip())))
    work = os.environ.get("VROOM_WORK") or os.path.join(root, "work")
    if not os.path.isdir(work):    # a worktree: the main checkout's work/
        common = subprocess.run(["git", "-C", root, "rev-parse", "--git-common-dir"], capture_output=True, text=True).stdout.strip()
        work = os.path.join(os.path.dirname(os.path.abspath(os.path.join(root, common))), "work")
    corpus = os.environ.get("CXX_CORPUS", " ".join([llvm + "/include/c++/v1", work + "/cxx/json/single_include",
                                                    work + "/cxx/json/tests/thirdparty/doctest"])).split()
    # system headers json reaches (glibc, clang's resource headers): only their queries, also
    # wrapped ones (glibc's __glibc_has_extension(x)), not every identifier
    sysdirs = os.environ.get("CXX_SYSCORPUS", "/usr/include " + llvm + "/lib/clang").split()
    for d in corpus + sysdirs:
        if not os.path.isdir(d):
            sys.exit(f"corpus directory missing: {d}")
    syslit = set()
    wre = re.compile(r"has_(builtin|attribute|feature|extension|cpp_attribute)\s*\(\s*([A-Za-z_][A-Za-z_0-9]*)\s*\)")
    for d in sysdirs:
        for f in glob.glob(d + "/**/*.h", recursive=True):
            try:
                t = open(f, errors="replace").read()
            except OSError:
                continue
            for kind, n in wre.findall(t):
                syslit.add(n)
    lit, ids, warns = set(), set(), set()
    qre = re.compile(r"(__has_(?:builtin|attribute|feature|extension|cpp_attribute|constexpr_builtin))\s*\(\s*([A-Za-z_0-9:]+)")
    for d in corpus:
        for f in glob.glob(d + "/**/*", recursive=True):
            if os.path.isdir(f):
                continue
            try:
                t = open(f, errors="replace").read()
            except OSError:
                continue
            for q, n in qre.findall(t):
                lit.add((q, n))
            warns.update(re.findall(r'__has_warning\s*\(\s*"([^"]+)"', t))
            warns.update(re.findall(r'"(-W[A-Za-z0-9+_=#-]+)"', t))     # wrapped: JSON_HEDLEY_HAS_WARNING("-W...")
            ids.update(re.findall(r"\b_*[A-Za-z][A-Za-z_0-9]*\b", t))
    # a name that is a macro (predefined for some target or standard, or one of clang's
    # builtin macros) would expand inside the query; _Pragma and friends swallow lines
    macros = set()
    for _, triple in TARGETS[:2]:
        for std in STDS:
            macros |= set(dm(CLANGXX, ["-target", triple, "-x", "c++", "-std=" + ("c++98" if std == 98 else f"c++{std}")]))
    macros |= {"defined", "_Pragma", "__VA_ARGS__", "__VA_OPT__", "__FILE__", "__LINE__", "__COUNTER__", "__DATE__",
               "__TIME__", "__TIMESTAMP__", "__BASE_FILE__", "__FILE_NAME__", "__INCLUDE_LEVEL__", "__building_module",
               "__is_identifier", "__is_target_arch", "__is_target_os", "__is_target_vendor", "__is_target_environment",
               "__is_target_variant_os", "__is_target_variant_environment", "__identifier"}
    names = sorted({n for n in ids | syslit | {n for _, n in lit} if n not in macros and not n.startswith("__has_")})
    lines = []
    for q in QUERIES:
        for n in names:
            if "::" in n and q not in ("__has_cpp_attribute", "__has_attribute"):
                continue
            lines.append(f'"{q}" "{n}" {q}({n})')
    for w in sorted(warns):
        lines.append(f'"__has_warning" "\\"{w}\\"" __has_warning("{w}")')
    ans = {}
    with tempfile.NamedTemporaryFile("w", suffix=".cpp", delete=False) as tf:
        tf.write("\n".join(lines) + "\n")
    cols = []
    for tgt, triple in TARGETS[:2]:
        for std in STDS:
            cols.append((tgt, std))
            name = "c++98" if std == 98 else f"c++{std}"
            r = subprocess.run([CLANGXX, "-target", triple, "-std=" + name, "-ferror-limit=0", "-E", "-P", "-x", "c++", tf.name],
                                 capture_output=True, text=True)
            if 'fatal error' in r.stderr:
                sys.exit('clang stopped: ' + next(l for l in r.stderr.splitlines() if 'fatal error' in l))
            outl = r.stdout.splitlines()
            if len(outl) != len(lines):
                sys.exit(f"{triple} {name}: {len(lines)} queries, {len(outl)} answers; first error: "
                         + next((l for l in r.stderr.splitlines() if "error" in l), "?"))
            for l in outl:
                p = l.split()
                if len(p) == 3 and re.fullmatch(r"[0-9]+L?", p[2]) and p[2] not in ("0", "0L"):
                    key = (p[0][1:-1], p[1][1:-1].replace('\\"', '"'))   # as the preprocessor spells the argument
                    ans.setdefault(key, {})[(tgt, std)] = p[2]
    os.unlink(tf.name)
    out = os.path.join(os.path.dirname(OUT), "ppdata-cxx-has.inc")
    with open(out, "w") as f:
        f.write(f"/* generated by src/tools/gen-cxxpredef.py; sorted for bsearch; columns: x86-64 Linux, aarch64 Linux x {STDS} */\n")
        f.write(f"static const struct {{ const char *q, *name; long v[2][{len(STDS)}]; }} has_tab_cxx[] = {{\n")
        for (q, n) in sorted(ans, key=lambda k: (k[0].encode(), k[1].encode())):   # strcmp order, for bsearch
            a = ans[(q, n)]
            v = ", ".join("{ " + ", ".join(a.get((tgt, std), "0").rstrip("L") for std in STDS) + " }" for tgt, _ in TARGETS[:2])
            f.write(f"\t{{ \"{q}\", \"{n.replace(chr(34), chr(92) + chr(34))}\", {{ {v} }} }},\n")
        f.write("};\n")
    print(f"wrote {out}: {len(ans)} nonzero answers from {len(names)} names")


if __name__ == "__main__":
    main()
