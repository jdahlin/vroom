#!/usr/bin/env python3
"""Generate the C++ front end's data tables (src/frontend/cplusplus/).

The front end is written against the C++ standard (docs/cxx-spec); where it
needs clang's own choices (the text of a diagnostic, which spellings clang
treats as keywords in which mode) the data is taken from clang once, here, as
AGENTS.md asks, and checked in:

  intro/diagnostic-messages.inc  every diagnostic of clang's Lex and Common
                                 components: name, class, default mapping,
                                 -W group, message format
  intro/diagnostic-groups.inc    every -W group with its subgroups
  lex/lex.key.inc                every keyword spelling in TokenKinds.def with
                                 clang's token name and its KEY* flags
  lex/lex.name.inc               XID_Start and XID_Continue as code point
                                 ranges (Unicode of this Python's unicodedata)
  lex/lex.charset.names.inc      Unicode's character names and name aliases
                                 for \\N{...}: the names a rule makes
                                 (CJK UNIFIED IDEOGRAPH-4E00) as ranges, the
                                 others front-coded in blocks; Hangul
                                 syllables are computed (Unicode 3.12)

Usage: src/tools/gen-cplusplus-data.py [--check] [TD_DIR]
TD_DIR is work/clang-td/VERSION (bench/clangdiag.py fetch VERSION); it must
also hold TokenKinds.def and TransformTypeTraits.def of the same version.
"""
import os
import re
import sys
import unicodedata

R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(R, 'bench'))
import clangdiag  # noqa: E402

OUT = os.path.join(R, 'src', 'frontend', 'cplusplus')
HEADER = '/* generated by src/tools/gen-cplusplus-data.py from %s: do not edit */\n'


def c_string(s):
    out = []
    for ch in s:
        if ch in '\\"':
            out.append('\\' + ch)
        elif ch == '\n':
            out.append('\\n')
        elif ord(ch) < 0x20 or ord(ch) > 0x7e:
            out.append('\\x%02x""' % ord(ch) if ord(ch) < 0x100 else ch)
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


# diagnostics from clang's other components that the front end issues in
# phases clang gives to Sema: [lex.fcon]/3's range of a floating-point literal
OTHER_DIAGNOSTICS = {'warn_float_overflow', 'warn_float_underflow'}


def diagnostics(td):
    diags, groups, _ = clangdiag.load(td)
    version = os.path.basename(td.rstrip('/'))
    names = sorted(n for n, r in diags.items()
                   if r['file'] in ('DiagnosticLexKinds.td', 'DiagnosticCommonKinds.td') or n in OTHER_DIAGNOSTICS)
    group_names = sorted({g[0] for g in groups.values()} | {diags[n]['group'] for n in names if diags[n]['group']})
    lines = [HEADER % f"clang {version}'s Diagnostic{{Lex,Common}}Kinds.td and a few of Sema's",
             '/* DIAGNOSTIC(name, class, default mapping, -W group or "", format) */']
    for n in names:
        r = diags[n]
        lines.append('DIAGNOSTIC(%s, %s, %s, %s, %s)' % (
            n, 'EXTENSION_WARNING' if r.get('extwarn') else r['class'].upper(),
            ('WARNING' if r.get('extwarn') and r['default'] == 'ignore' else r['default']).upper().replace('-', 'NONE'),
            c_string(r['group'] or ''), c_string(r['text'])))
    by_def = {d: g for d, g in groups.items()}
    glines = [HEADER % f"clang {version}'s DiagnosticGroups.td",
              '/* DIAGNOSTIC_GROUP(name, subgroups separated by spaces) */']
    flag_subs = {}
    for d, (flag, subs) in by_def.items():
        flag_subs.setdefault(flag, set()).update(by_def[s][0] for s in subs if s in by_def)
    for g in group_names:
        glines.append('DIAGNOSTIC_GROUP(%s, %s)' % (c_string(g), c_string(' '.join(sorted(flag_subs.get(g, ()))))))
    return '\n'.join(lines) + '\n', '\n'.join(glines) + '\n'


# TokenKinds.def's macros, reduced to (spelling, clang token name, flags)
KEYWORD_MACROS = {
    'KEYWORD': lambda a: (a[0], 'kw_' + a[0], a[1]),
    'CXX11_KEYWORD': lambda a: (a[0], 'kw_' + a[0], 'KEYCXX11|' + a[1]),
    'CXX20_KEYWORD': lambda a: (a[0], 'kw_' + a[0], 'KEYCXX20|' + a[1]),
    'C99_KEYWORD': lambda a: (a[0], 'kw_' + a[0], 'KEYC99|' + a[1]),
    'C23_KEYWORD': lambda a: (a[0], 'kw_' + a[0], 'KEYC23|' + a[1]),
    'COROUTINES_KEYWORD': lambda a: (a[0], 'kw_' + a[0], 'KEYCXX20|KEYCOROUTINES'),
    'MODULES_KEYWORD': lambda a: (a[0], 'kw_' + a[0], 'KEYMODULES'),
    'TYPE_TRAIT_1': lambda a: (a[0], 'kw_' + a[0], a[2]),
    'TYPE_TRAIT_2': lambda a: (a[0], 'kw_' + a[0], a[2]),
    'TYPE_TRAIT_N': lambda a: (a[0], 'kw_' + a[0], a[2]),
    'ARRAY_TYPE_TRAIT': lambda a: (a[0], 'kw_' + a[0], a[2]),
    'UNARY_EXPR_OR_TYPE_TRAIT': lambda a: (a[0], 'kw_' + a[0], a[2]),
    'CXX11_UNARY_EXPR_OR_TYPE_TRAIT': lambda a: (a[0], 'kw_' + a[0], 'KEYCXX11|' + a[2]),
    'EXPRESSION_TRAIT': lambda a: (a[0], 'kw_' + a[0], a[2]),
    'ALIAS': lambda a: (a[0].strip('"'), 'kw_' + a[1], a[2]),
    'CXX_KEYWORD_OPERATOR': lambda a: (a[0], a[1], 'KEYCXX|OPERATOR'),
    'TESTING_KEYWORD': lambda a: (a[0], 'kw_' + a[0], a[1]),
}
# the flags lex.key.cpp models; every other KEY* (OpenCL, HLSL, CUDA, AltiVec,
# Objective-C, ...) never holds for C++ on our targets
KNOWN_FLAGS = ['KEYALL', 'KEYC99', 'KEYC23', 'KEYCXX', 'KEYCXX11', 'KEYCXX20', 'KEYGNU', 'KEYMS', 'KEYMSCOMPAT',
               'KEYNOCXX', 'KEYNOMS18', 'KEYCOROUTINES', 'KEYMODULES', 'BOOLSUPPORT', 'WCHARSUPPORT',
               'CHAR8SUPPORT', 'HALFSUPPORT', 'OPERATOR']


def keywords(td):
    text = open(os.path.join(td, 'TokenKinds.def')).read()
    text = text.replace('#include "clang/Basic/TransformTypeTraits.def"',
                        open(os.path.join(td, 'TransformTypeTraits.def')).read())
    text = re.sub(r'//[^\n]*', '', text)
    out = {}
    for m in re.finditer(r'^\s*(\w+)\(([^)]*)\)', text, re.M):
        macro, args = m.group(1), [a.strip() for a in m.group(2).split(',')]
        if macro == 'TRANSFORM_TYPE_TRAIT_DEF':
            spelling, name, flags = '__' + args[1], 'kw___' + args[1], 'KEYCXX'
        elif macro in KEYWORD_MACROS:
            if not args[0] or args[0].startswith('/*'):
                continue
            spelling, name, flags = KEYWORD_MACROS[macro](args)
        else:
            continue
        bits = [f for f in re.split(r'[|()\s]+', flags) if f and f != '0']
        mapped = [('KEYWORD_' + f) if f in KNOWN_FLAGS else 'KEYWORD_OTHER' for f in bits]
        out[spelling] = (name, '|'.join(sorted(set(mapped))) or '0')
    version = os.path.basename(td.rstrip('/'))
    lines = [HEADER % f"clang {version}'s TokenKinds.def and TransformTypeTraits.def",
             '/* KEYWORD(spelling, clang token name, flags) in spelling order */']
    for s in sorted(out):
        lines.append('KEYWORD(%s, %s, %s)' % (c_string(s), c_string(out[s][0]), out[s][1]))
    return '\n'.join(lines) + '\n'


def ranges(pred):
    out, start = [], None
    for c in range(0x80, 0x110000):
        ok = pred(c)
        if ok and start is None:
            start = c
        elif not ok and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def xid():
    # str.isidentifier() is XID_Start (plus '_') for the first character and
    # XID_Continue for the others, without normalization
    lines = [HEADER % f"Python's unicodedata (Unicode {unicodedata.unidata_version})",
             f'#define XID_UNICODE_VERSION "{unicodedata.unidata_version}"']
    for name, pred in (('xid_start', lambda c: (c < 0xD800 or c > 0xDFFF) and chr(c).isidentifier()),
                       ('xid_continue', lambda c: (c < 0xD800 or c > 0xDFFF) and ('a' + chr(c)).isidentifier())):
        rs = ranges(pred)
        lines.append('static const code_point_range %s_ranges[%d] = {' % (name, len(rs)))
        for i in range(0, len(rs), 4):
            lines.append('    ' + ' '.join('{0x%04X, 0x%04X},' % r for r in rs[i:i + 4]))
        lines.append('};')
    return '\n'.join(lines) + '\n'


BASE64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'


def work_dir():
    """work/ of this checkout, or of the main checkout from a git worktree"""
    if os.path.isdir(os.path.join(R, 'work', 'unicode')):
        return os.path.join(R, 'work')
    import subprocess
    common = subprocess.run(['git', '-C', R, 'rev-parse', '--path-format=absolute', '--git-common-dir'],
                            capture_output=True, text=True).stdout.strip()
    return os.path.join(os.path.dirname(common), 'work') if common else os.path.join(R, 'work')


def name_aliases():
    """NameAliases.txt of this Python's Unicode version, fetched once into
    work/unicode/VERSION/"""
    version = unicodedata.unidata_version
    path = os.path.join(work_dir(), 'unicode', version, 'NameAliases.txt')
    if not os.path.exists(path):
        import subprocess
        os.makedirs(os.path.dirname(path), exist_ok=True)
        subprocess.run(['curl', '-fsSL', '-o', path, f'https://www.unicode.org/Public/{version}/ucd/NameAliases.txt'],
                       check=True)
    out = []
    for line in open(path):
        line = line.split('#')[0].strip()
        if line:
            cp, alias, _kind = line.split(';')
            out.append((alias, int(cp, 16)))
    return out


def names():
    explicit, rules = [], {}
    for cp in range(0x110000):
        n = unicodedata.name(chr(cp), None)
        if not n or n.startswith('HANGUL SYLLABLE '):
            continue
        prefix, _, tail = n.rpartition('-')
        if prefix and tail in ('%04X' % cp, '%05X' % cp):
            r = rules.setdefault(prefix, [])
            if r and r[-1][1] == cp - 1:
                r[-1][1] = cp
            else:
                r.append([cp, cp])
            continue
        explicit.append((n, cp))
    explicit += name_aliases()
    explicit.sort()
    block = 32
    blob, offsets, prev = [], [], ''
    position = 0
    for i, (n, cp) in enumerate(explicit):
        if i % block == 0:
            offsets.append(position)
            p = 0
        else:
            p = 0
            while p < min(len(n), len(prev), 63) and n[p] == prev[p]:
                p += 1
        entry = BASE64[p] + n[p:] + ';' + ''.join(BASE64[(cp >> s) & 63] for s in (18, 12, 6, 0))
        blob.append(entry)
        position += len(entry)
        prev = n
    text = ''.join(blob)
    lines = [HEADER % f"Python's unicodedata and NameAliases.txt (Unicode {unicodedata.unidata_version})",
             '/* names a rule makes: PREFIX-XXXX for each code point of the ranges */',
             'static constexpr struct named_range {', '    const char *prefix;', '    uint32_t first, last;',
             '} unicode_named_ranges[] = {']
    for prefix in sorted(rules):
        for a, b in rules[prefix]:
            lines.append('    {"%s", 0x%04X, 0x%04X},' % (prefix, a, b))
    lines += ['};', '',
              '/* the other names and the name aliases, sorted; each entry is the length of',
              '   the prefix it shares with the previous one (0 at a block start), in the',
              '   base64 alphabet, the rest of the name, \';\' and the code point in four',
              '   base64 digits */',
              '#define UNICODE_NAME_COUNT %d' % len(explicit),
              '#define UNICODE_NAME_BLOCK %d' % block,
              'static constexpr uint32_t unicode_name_block_offsets[] = {']
    for i in range(0, len(offsets), 10):
        lines.append('    ' + ' '.join('%d,' % o for o in offsets[i:i + 10]))
    lines += ['};', 'static constexpr char unicode_names[] =']
    for i in range(0, len(text), 96):
        lines.append('    "%s"' % text[i:i + 96])
    lines[-1] += ';'
    return '\n'.join(lines) + '\n'


# [cpp.predefined]: clang's predefined macros for the documented target, in
# each mode the front end has: edition x GNU (-std=gnu++NN) x -fms-extensions
# x char8_t switched from the edition's default (-fchar8_t / -fno-char8_t)
EDITIONS = ['98', '11', '14', '17', '20', '23', '26']
PREDEFINE_TRIPLE = 'aarch64-unknown-linux-gnu'


def predefined_set(clang, edition, gnu, ms, char8_switched):
    import subprocess
    args = [clang, '-cc1', '-triple', PREDEFINE_TRIPLE, '-x', 'c++',
            f'-std={"gnu" if gnu else "c"}++{edition}', '-dM', '-E', '/dev/null']
    if ms:
        args.append('-fms-extensions')
    if char8_switched:
        args.append('-fno-char8_t' if int(edition) >= 20 and edition != '98' else '-fchar8_t')
    out = subprocess.run(args, capture_output=True, text=True, check=True).stdout
    d = {}
    for line in out.splitlines():
        if line.startswith('#define '):
            name, _, body = line[8:].partition(' ')
            d[name] = body
    return d


def predefined(clang='clang-23'):
    rows = {}
    for e, edition in enumerate(EDITIONS):
        for gnu in (0, 1):
            for ms in (0, 1):
                for char8 in (0, 1):
                    variant = ((e * 2 + gnu) * 2 + ms) * 2 + char8
                    for name, body in predefined_set(clang, edition, gnu, ms, char8).items():
                        rows[(name, body)] = rows.get((name, body), 0) | (1 << variant)
    version = subprocess_version(clang)
    lines = [HEADER % f'{version} -cc1 -triple {PREDEFINE_TRIPLE} -dM -E',
             '/* PREDEFINED_MACRO(variants, name, replacement): defined in the modes',
             '   whose bit is set, bit ((edition * 2 + gnu) * 2 + ms) * 2 + char8_t',
             '   switched, editions 98 11 14 17 20 23 26 */']
    for (name, body), mask in sorted(rows.items()):
        lines.append(f'PREDEFINED_MACRO(0x{mask:014x}ull, {c_string(name)}, {c_string(body)})')
    return '\n'.join(lines) + '\n'


def subprocess_version(clang):
    import subprocess
    out = subprocess.run([clang, '--version'], capture_output=True, text=True).stdout
    m = re.search(r'clang version (\S+)', out)
    return f'clang {m.group(1)}' if m else clang


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    check = '--check' in sys.argv
    td = args[0] if args else clangdiag.td_dir()
    messages, groups = diagnostics(td)
    files = {
        'intro/diagnostic-messages.inc': messages,
        'intro/diagnostic-groups.inc': groups,
        'lex/lex.key.inc': keywords(td),
        'lex/lex.name.inc': xid(),
        'lex/lex.charset.names.inc': names(),
        'cpp/cpp.predefined.inc': predefined(),
    }
    stale = 0
    for rel, text in files.items():
        path = os.path.join(OUT, rel)
        old = open(path).read() if os.path.exists(path) else None
        if old == text:
            continue
        if check:
            print(f'{rel}: out of date', file=sys.stderr)
            stale += 1
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, 'w').write(text)
        print(f'wrote {rel}')
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main())
