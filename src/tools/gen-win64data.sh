#!/bin/sh
# gen-win64data.sh   (writes frontend/pp/ppdata-win64.inc and frontend/c/attrnames-win64.inc)
#
# What clang answers for Windows x64 through MinGW-w64 (x86_64-w64-mingw32,
# PLAN-win64.md WIN1), in files of their own as gen-x86data.sh does for
# x86-64 Linux: the predefined macros and their -dD order, the feature-test
# queries (__has_builtin(x), ...) and the attribute names clang knows.  The
# other targets' tables are not touched.
#
# Query candidates: every (query, name) of has_tab in ppdata.inc and
# has_tab_x86 in ppdata-x86.inc, the literal queries in clang's resource
# headers and the MinGW-w64 sysroot's headers, and every identifier in those
# headers.  Attribute candidates: clang's spelling list (attr_spellings in
# attrnames.inc).  vcc itself never runs clang.
#
#   SYSROOT=/path/to/llvm-mingw-...-x86_64 src/tools/gen-win64data.sh   (or VCC_MINGW_SYSROOT)
#
# SYSROOT is the llvm-mingw tree (its x86_64-w64-mingw32/include is read);
# default: work/llvm-mingw/llvm-mingw-* of the main checkout.
set -e
CL=${CLANG:-clang}
TOOLS=$(dirname "$0")
D=$TOOLS/../frontend/pp
T=${KEEP:-$(mktemp -d)}; mkdir -p $T; [ -n "$KEEP" ] || trap "rm -rf $T" EXIT
SYSROOT=${SYSROOT:-$VCC_MINGW_SYSROOT}
if [ -z "$SYSROOT" ]; then
	W=$(cd "$TOOLS" && git rev-parse --path-format=absolute --git-common-dir)/../work
	SYSROOT=$(ls -d "$W"/llvm-mingw/llvm-mingw-*-x86_64 2>/dev/null | tail -1)
fi
[ -d "$SYSROOT/x86_64-w64-mingw32/include" ] || { echo "gen-win64data.sh: no MinGW sysroot (set SYSROOT)" >&2; exit 1; }
TGT=--target=x86_64-w64-mingw32
# the base table: -O2 without PIE, PIC and CFI, as the other tables (the driver adds what differs)
FX="$TGT -std=gnu11 -O2 -fno-PIE -fno-asynchronous-unwind-tables -fno-unwind-tables"
cstr() { sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/	"/' -e 's/$/\\n"/'; }
RESINC=$($CL -print-resource-dir)/include
INC="$RESINC $SYSROOT/x86_64-w64-mingw32/include"

exec 3> "$D/ppdata-win64.inc"
{
	echo "/* generated by gen-win64data.sh from $($CL --version | head -1) */"
	echo "#ifdef PPDATA_WIN64_PREDEF	/* driver/predef.c */"
	echo "static const char predef_x86_64_win64[] ="
	$CL $FX -dM -E -x c /dev/null | LC_ALL=C sort | cstr
	echo "	;"
	echo "static const char *const predef_order_win64[] = {"
	python3 $TOOLS/gen-ppdata-order.py $CL "$FX" "$FX -O0" "$FX -Os" "$TGT" "$TGT -O2 -fPIC" "$TGT -fno-PIE" "$TGT -std=c99" "$TGT -std=c23" "$TGT -std=c89" "$TGT -ffast-math" "$TGT -fshort-wchar" "$TGT -funsigned-char" "$TGT -pthread" "$TGT -municode"
	echo "};"
	echo "#endif"
} >&3

Q='__has_(attribute|builtin|feature|extension|c_attribute|cpp_attribute|declspec_attribute|constexpr_builtin)|__is_target_(arch|os|vendor|environment|variant_os|variant_environment)'
grep -rhoE "($Q)[[:space:]]*\\([[:space:]]*[A-Za-z_0-9:-]+" --include='*.h' $INC 2>/dev/null | tr -d ' \t' > $T/lit
sed -n 's/^	{ "\([^"]*\)", "\([^"]*\)", .*/\1(\2/p' $D/ppdata.inc $D/ppdata-x86.inc >> $T/lit
{
	grep -rhoE '[A-Za-z_][A-Za-z_0-9]*' $INC 2>/dev/null
	sed 's/^[^(]*(//' $T/lit
} | LC_ALL=C sort -u > $T/ids0
$CL $FX -dM -E -x c /dev/null | awk '{ sub(/\(.*/, "", $2); print $2 }' | LC_ALL=C sort -u > $T/macros
LC_ALL=C comm -23 $T/ids0 $T/macros | grep -vE '^(__has_|__is_target_|__building_module$|_Pragma$|defined$|__FILE__$|__LINE__$|__COUNTER__$|__DATE__$|__TIME__$|__TIMESTAMP__$|__BASE_FILE__$|__FILE_NAME__$|__INCLUDE_LEVEL__$|__is_identifier$)' > $T/ids
for q in __has_builtin __has_attribute __has_feature __has_extension __has_c_attribute __has_declspec_attribute __has_constexpr_builtin; do
	sed "s/.*/\"$q\" \"&\" $q(&)/" $T/ids
done > $T/q.c
sed -n 's/^\(__is_target_[a-z_]*\)(\(.*\)$/"\1" "\2" \1(\2)/p' $T/lit | LC_ALL=C sort -u >> $T/q.c
sed -n 's/^\(__has_[a-z_]*\)(\(.*::.*\)$/"\1" "\2" \1(\2)/p' $T/lit | LC_ALL=C sort -u >> $T/q.c
{
	echo "#ifdef PPDATA_WIN64_HAS	/* frontend/pp/builtin.c */"
	echo "/* Windows x64 (MinGW-w64): the nonzero answers, sorted by (query, name) for bsearch */"
	echo "static const struct { const char *q, *name; int v; } has_tab_win64[] = {"
	$CL $FX -ferror-limit=0 -E -P -x c $T/q.c 2>/dev/null | awk 'NF==3 && $3 ~ /^[0-9]+L?$/ && $3 != "0"' |
		LC_ALL=C sort -u -k1,1 -k2,2 | awk '{ printf "\t{ %s, %s, %s },\n", $1, $2, $3 }'
	echo "};"
	echo "#endif"
} >&3

# attributes: the names of clang's spelling list it answers nonzero for
awk '/attr_spellings\[\] = \{/{f=1;next} f&&/^\};/{exit} f' $D/../c/attrnames.inc | sed 's/^	"\(.*\)",$/\1/' > $T/spell
{ sed 's/^/#undef /' $T/spell; sed 's/.*/"&" __has_attribute(&)/' $T/spell; } > $T/qa.c
{ sed 's/^/#undef /' $T/spell; sed 's/.*/"&" __has_c_attribute(&)/' $T/spell; sed 's/.*/"gnu::&" __has_c_attribute(gnu::&)/' $T/spell
  sed 's/.*/"clang::&" __has_c_attribute(clang::&)/' $T/spell; } > $T/qc.c
exec > "$D/../c/attrnames-win64.inc"
echo "/* generated by gen-win64data.sh from $($CL --version | head -1); sorted for bsearch */"
echo "/* Windows x64 (MinGW-w64): GNU attribute names clang knows (__has_attribute != 0) */"
echo "static const char *const gnu_attrs_win64[] = {"
$CL $TGT -E -P -x c $T/qa.c 2>/dev/null | awk 'NF==2 && $2 != "0" { printf "\t%s,\n", $1 }' | LC_ALL=C sort -u
echo "};"
echo "/* [[name]], [[gnu::name]], [[clang::name]] (__has_c_attribute != 0) */"
echo "static const char *const c_attrs_win64[] = {"
$CL $TGT -E -P -x c $T/qc.c 2>/dev/null | awk 'NF==2 && $2 != "0" { printf "\t%s,\n", $1 }' | LC_ALL=C sort -u
echo "};"
