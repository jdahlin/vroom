#!/usr/bin/env python3
"""gen-libbuiltins.py: clang's library builtins -> src/cc/libbuiltins.inc

    src/cc/gen-libbuiltins.py [Builtins.inc]

Taken from clang once (no clang at run time): every __builtin_X that clang's
Builtins.inc marks 'F' (a library function with the __builtin_ prefix), as
{ "__builtin_X", "X", "<clang type string>" }, sorted by name.  vcc declares
one on first use with that prototype, under the symbol X (cc/decl.c
lib_builtin); one whose type string it cannot read stays unknown.

Also libfuncs.inc: every library function clang knows with its header (a
lowercase 'f', HeaderDesc other than NO_HEADER) as { "X", "header.h",
"<type string>", gnu }, gnu = 1 for clang's ALL_GNU_LANGUAGES (only under
-std=gnu*).  A call to an undeclared one is clang's "call to undeclared
library function 'X' with type T" with the note "include the header <H>"
(cc/decl.c lib_func).
"""
import os, re, sys

src = sys.argv[1] if len(sys.argv) > 1 else '/opt/homebrew/opt/llvm/include/clang/Basic/Builtins.inc'
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'libbuiltins.inc')
# the subset of clang's type encoding that cc/decl.c lb_type reads: only those
# entries are written, so the table is also vcc's __has_builtin answer for them
TYPE = r'(?:[SUIX]*(?:L{0,3}i|[SUI]*[vbcsfzYwPWZ]|Ld|d))(?:\*\d*|[CDR])*'
SIG = re.compile(rf'^(?:{TYPE})+\.?$')
ent, fns = {}, {}
text = open(src).read()
hdr = dict(re.findall(r'HEADER\((\w+), "([^"]+)"\)', open(os.path.join(os.path.dirname(src), 'BuiltinHeaders.def')).read()))
for m in re.finditer(r'StrOffsets\{\d+ /\* (\S+) \*/, \d+ /\* (.*?) \*/, \d+ /\* (.*?) \*/, \d+\}, HeaderDesc::(\w+), (\w+)',
                     text):
    name, sig, attrs, h, langs = m.groups()
    if name.startswith('__builtin_') and 'F' in attrs and langs in ('ALL_LANGUAGES', 'ALL_GNU_LANGUAGES') and SIG.match(sig):
        ent[name] = (name[10:], sig, attrs)
    if not name.startswith('__builtin_') and 'f' in attrs and h in hdr and langs in ('ALL_LANGUAGES', 'ALL_GNU_LANGUAGES') \
            and SIG.match(sig):
        fns[name] = (hdr[h], sig, int(langs == 'ALL_GNU_LANGUAGES'))
with open(out, 'w') as f:
    f.write('/* generated by gen-libbuiltins.py from clang\'s Builtins.inc: do not edit */\n')
    for n in sorted(ent):
        lib, sig, attrs = ent[n]
        f.write(f'\t{{ "{n}", "{lib}", "{sig}" }},\n')
print(f'{out}: {len(ent)} library builtins')
out2 = os.path.join(os.path.dirname(out), 'libfuncs.inc')
with open(out2, 'w') as f:
    f.write('/* generated by gen-libbuiltins.py from clang\'s Builtins.inc: do not edit */\n')
    for n in sorted(fns):
        h, sig, gnu = fns[n]
        f.write(f'\t{{ "{n}", "{h}", "{sig}", {gnu} }},\n')
print(f'{out2}: {len(fns)} library functions with a header')
