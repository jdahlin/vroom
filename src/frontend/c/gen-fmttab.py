#!/usr/bin/env python3
"""Generate fmttab.inc: clang's -Wformat answers for printf conversions.

For every length modifier x conversion x argument type (a representative of
each class vcc maps an argument to) clang is asked once per target; the table
keeps, per specification, the expected type as clang prints it, whether the
length modifier is invalid with the conversion, and per argument type whether
it mismatches and the fix-it clang suggests.  Run once (needs clang):
    src/frontend/c/gen-fmttab.py > src/frontend/c/fmttab.inc
"""
import os, re, subprocess, sys, tempfile

CLANG = os.environ.get('CLANG', '/opt/homebrew/opt/llvm/bin/clang')
LENS = ['', 'hh', 'h', 'l', 'll', 'j', 'z', 't', 'L', 'q', 'w', 'I', 'I32', 'I64']
CONVS = 'd i o u x X b B c s p f F e E g G a A n C S D O U'.split()
# the argument classes, in the order of FMT_T_* in fmt.c
TYPES = ['char', 'signed char', 'unsigned char', 'short', 'unsigned short', 'int', 'unsigned int',
         'long', 'unsigned long', 'long long', 'unsigned long long', 'float', 'double', 'long double',
         'char *', 'const char *', 'signed char *', 'unsigned char *', 'void *', 'const void *',
         'int *', 'long *', '_Bool', '__int128', 'short *', 'unsigned int *',
         'struct S *', 'enum U', 'enum I', 'unsigned __int128', 'long long *', 'signed char **']
TARGETS = [('linux', 'aarch64-linux-gnu'), ('darwin', 'arm64-apple-macosx14.0')]


def probe(target):
    specs = [l + c for l in LENS for c in CONVS]
    lines = ['int pf(const char *f, ...) __attribute__((format(printf, 1, 2)));',
             'struct S; enum U { U0 }; enum I { I0 = -1 };']
    for i, t in enumerate(TYPES):
        lines.append(f'extern {t} v{i};')
    lines.append('void t(void) {')
    first = len(lines) + 1
    cases = []
    for s in specs:
        for i in range(len(TYPES)):
            cases.append((s, i))
            lines.append(f'pf("%{s}", v{i});')
    lines.append('}')
    with tempfile.NamedTemporaryFile('w', suffix='.c', delete=False) as f:
        f.write('\n'.join(lines) + '\n')
        path = f.name
    out = subprocess.run([CLANG, '--target=' + target, '-fsyntax-only', '-ferror-limit=0',
                          '-fno-color-diagnostics', '-fdiagnostics-parseable-fixits', path],
                         capture_output=True, text=True).stderr
    os.unlink(path)
    res = {}
    last = None
    for l in out.split('\n'):
        m = re.match(r'.*?:(\d+):(\d+): warning: (.*)', l)
        if m:
            key = cases[int(m.group(1)) - first]
            last = [m.group(3), None]
            res.setdefault(key, []).append(last)
            continue
        m = re.match(r'fix-it:.*:\{\d+:\d+-\d+:\d+\}:"(.*)"', l)
        if m and last:
            last[1] = m.group(1)
    return specs, res


def main():
    pool = ['']
    out = ['/* generated by gen-fmttab.py from clang: do not edit */',
           f'#define FMT_NTY {len(TYPES)}']
    tabs = []
    for name, target in TARGETS:
        specs, res = probe(target)
        rows = []
        for s in specs:
            badlen, exp = 0, None
            fix = []
            for i in range(len(TYPES)):
                code = 0
                for msg, fx in res.get((s, i), []):
                    if msg.startswith('invalid conversion specifier'):
                        continue    # (D/O/U outside Darwin)
                    if msg.startswith('length modifier'):
                        badlen = 1
                    elif msg.startswith('using '):
                        code = 255
                    else:
                        m = re.match(r"format specifies type '(.*?)'( \(aka '.*?'\))? but the argument has (underlying )?type", msg)
                        if not m:
                            sys.exit(f'unknown message {msg!r}')
                        e = "'" + m.group(1) + "'" + (m.group(2) or '')
                        if exp is not None and exp != e:
                            sys.exit(f'{s}: {e} vs {exp}')
                        exp = e
                        if fx is None:
                            code = 1
                        else:
                            if not fx.startswith('%'):
                                sys.exit(f'fix-it {fx!r}')
                            fx = fx[1:]
                            if fx not in pool:
                                pool.append(fx)
                            code = pool.index(fx) + 1
                fix.append(code)
            rows.append((s, badlen, exp, fix))
        tabs.append((name, rows))
    if len(pool) + 1 >= 255:
        sys.exit('fix-it pool too large')
    out.append('static const char *const fmt_fix[] = { ' + ', '.join(f'"{p}"' for p in pool) + ' };')
    for name, rows in tabs:
        out.append(f'static const fmtspec fmt_{name}[] = {{')
        for s, badlen, exp, fix in rows:
            e = 'NULL' if exp is None else '"' + exp.replace('"', '\\"') + '"'
            out.append(f'\t{{ "{s}", {badlen}, {e}, {{ ' + ', '.join(map(str, fix)) + ' } },')
        out.append('};')
    print('\n'.join(out))


main()
