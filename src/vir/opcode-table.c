const char *const vir_type_names[VIR_TYPE_COUNT] = { "void", "i32", "i64", "f32", "f64", "ptr", "multi", "f32x4", "i32x4", "f64x2", "i64x2" };
const char *const vir_integer_condition_names[10] = { "eq", "ne", "slt", "sle", "sgt", "sge", "ult", "ule", "ugt", "uge" };
const char *const vir_float_condition_names[8] = { "oeq", "une", "olt", "ole", "ogt", "oge", "uno", "one" };

const vir_opcode_info *vir_opcode_find(const char *s, size_t n)
{
	for (int i = 0; i < 128; i++) {
		const char *nm = vir_opcode_table[i].name;

		if (nm && strlen(nm) == n && !memcmp(nm, s, n))
			return &vir_opcode_table[i];
	}
	return NULL;
}

bool vir_opcode_is_constant(uint32_t op) { return op >= VIR_OP_ICONST && op <= VIR_OP_LABELADDR; }
bool vir_opcode_is_terminator(uint32_t op) { return op >= VIR_OP_BR && op <= VIR_OP_TRAP && vir_opcode_table[op].name; }

uint32_t vir_type_size(uint32_t ty)
{
	return ty == VIR_TYPE_I32 || ty == VIR_TYPE_F32 ? 4 : ty == VIR_TYPE_I64 || ty == VIR_TYPE_F64 || ty == VIR_TYPE_PTR ? 8 : vir_type_is_vector(ty) ? 16 : 0;
}

uint32_t vir_operand_type_fixed(uint32_t op, uint32_t ty, uint32_t k)
{
	switch (vir_opcode_table[op & 255].operand_kinds[k > 2 ? 2 : k]) {
	case VIR_OPERAND_KIND_T: return ty;
	case VIR_OPERAND_KIND_I32: return VIR_TYPE_I32;
	case VIR_OPERAND_KIND_F32: return VIR_TYPE_F32;
	case VIR_OPERAND_KIND_I64: case VIR_OPERAND_KIND_CONSTV: return VIR_TYPE_I64;
	case VIR_OPERAND_KIND_F64: return VIR_TYPE_F64;
	case VIR_OPERAND_KIND_PTR: return VIR_TYPE_PTR;
	case VIR_OPERAND_KIND_VI: return vir_type_vector_integer(ty);
	case VIR_OPERAND_KIND_VF: return vir_type_vector_float(ty);
	case VIR_OPERAND_KIND_ELEM: return vir_type_element(ty);
	case VIR_OPERAND_KIND_VLANES: return ty == VIR_TYPE_I32 ? VIR_TYPE_I32X4 : ty == VIR_TYPE_I64 ? VIR_TYPE_I64X2 : ty == VIR_TYPE_F32 ? VIR_TYPE_F32X4 : ty == VIR_TYPE_F64 ? VIR_TYPE_F64X2 : VIR_TYPE_VOID;
	case VIR_OPERAND_KIND_VRED: return ty == VIR_TYPE_I32 ? VIR_TYPE_I32X4 : ty == VIR_TYPE_I64 ? VIR_TYPE_I64X2 : VIR_TYPE_VOID;
	case VIR_OPERAND_KIND_BITC: return ty == VIR_TYPE_I32 ? VIR_TYPE_F32 : ty == VIR_TYPE_F32 ? VIR_TYPE_I32 : ty == VIR_TYPE_I64 ? VIR_TYPE_F64 : ty == VIR_TYPE_F64 ? VIR_TYPE_I64 : VIR_TYPE_VOID;
	default: return VIR_TYPE_VOID;
	}
}
