static inline uint16_t pe_rd16(const void *p) { uint16_t v; memcpy(&v, p, 2); return v; }
static inline uint32_t pe_rd32(const void *p) { uint32_t v; memcpy(&v, p, 4); return v; }
static inline uint64_t pe_rd64(const void *p) { uint64_t v; memcpy(&v, p, 8); return v; }
static inline void pe_wr16(void *p, uint16_t v) { memcpy(p, &v, 2); }
static inline void pe_wr32(void *p, uint32_t v) { memcpy(p, &v, 4); }
static inline void pe_wr64(void *p, uint64_t v) { memcpy(p, &v, 8); }

/* a COFF section header, decoded */
typedef struct {
	char name[9];			/* the 8 bytes, NUL-terminated (a /N long name is resolved by the reader) */
	uint32_t virtual_size, virtual_address, size_of_raw_data, pointer_to_raw_data;
	uint32_t pointer_to_relocations, pointer_to_linenumbers;
	uint32_t number_of_relocations;	/* the 16-bit field, or the overflow count */
	uint16_t number_of_linenumbers;
	uint32_t characteristics;
} coff_section_header;

/* alignment of a section from its characteristics (llvm::object::coff_section::getAlignment) */
static inline uint32_t coff_section_alignment(uint32_t characteristics)
{
	if (characteristics & IMAGE_SCN_TYPE_NO_PAD)
		return 1;
	uint32_t shift = (characteristics >> 20) & 0xf;
	return shift ? 1u << (shift - 1) : 16;
}

